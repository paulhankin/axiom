#!/usr/bin/env python3
"""Generates std/net/hpack/tables.ax (the static table and Huffman code of RFC
7541, appendices A and B) and std/net/hpack/testdata/cases.txt (header lists
and how Python's hpack encodes them), from the hpack package:

    pip install hpack
    tools/gen_hpack.py

cases.txt: "reset" starts a new encoder and decoder; "size N" makes the
encoder's table N bytes; otherwise "HEX<TAB>name: value<TAB>..." is a block
and the header list it encodes.
"""
import os
import random
import subprocess

from hpack import Encoder
from hpack.huffman_constants import REQUEST_CODES, REQUEST_CODES_LENGTH
from hpack.table import HeaderTable

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
static = HeaderTable.STATIC_TABLE
assert len(static) == 61 and len(REQUEST_CODES) == 257


def esc(b):
    return ''.join(chr(c) if 0x20 <= c < 0x7f and c not in (0x22, 0x5c) else '\\x%02x' % c for c in b)


with open(os.path.join(root, 'std', 'net', 'hpack', 'tables.ax'), 'w') as f:
    f.write('// Generated by tools/gen_hpack.py: RFC 7541 appendices A and B. Do not edit.\n\n')
    f.write('/// The static table (index 1 is entry 0).\n')
    f.write('pub let STATIC_NAMES: [61][]u8 = [%s];\n' % ', '.join('"%s"' % esc(n) for n, _ in static))
    f.write('pub let STATIC_VALUES: [61][]u8 = [%s];\n\n' % ', '.join('"%s"' % esc(v) for _, v in static))
    f.write('/// The Huffman code of each byte, and of the end of string (256).\n')
    f.write('pub let HUFF_CODES: [257]u32 = [%s];\n' % ', '.join(str(c) for c in REQUEST_CODES))
    f.write('pub let HUFF_LENS: [257]u8 = [%s];\n' % ', '.join(str(c) for c in REQUEST_CODES_LENGTH))
exe = os.path.join(root, 'cmd', 'axiom', 'build', 'axiom')
if os.path.exists(exe):
    subprocess.run([exe, 'fmt', os.path.join(root, 'std', 'net', 'hpack', 'tables.ax')], check=False)

rng = random.Random(7541)
words = ['a', 'text/html', 'gzip, deflate', 'en-US', 'max-age=0', 'keep-alive', 'no-cache', 'Mozilla/5.0',
         'custom-value', 'x' * 60, 'session=abc123; theme=dark', '/index.html', '/api/v1/items?id=42']
names = [':method', ':path', ':authority', ':scheme', ':status', 'accept', 'accept-encoding', 'user-agent',
         'cookie', 'cache-control', 'x-custom', 'x-request-id', 'content-type', 'etag', 'date']
lines = []


def block(enc, headers):
    b = enc.encode(headers)
    lines.append(b.hex() + '\t' + '\t'.join('%s: %s' % (n, v) for n, v in headers))


# the RFC's examples C.3 and C.5 (the request and response sequences)
enc = Encoder()
lines.append('reset')
block(enc, [(':method', 'GET'), (':scheme', 'http'), (':path', '/'), (':authority', 'www.example.com')])
block(enc, [(':method', 'GET'), (':scheme', 'http'), (':path', '/'), (':authority', 'www.example.com'),
            ('cache-control', 'no-cache')])
block(enc, [(':method', 'GET'), (':scheme', 'https'), (':path', '/index.html'), (':authority', 'www.example.com'),
            ('custom-key', 'custom-value')])
enc = Encoder()
enc.header_table_size = 256
lines.append('reset')
lines.append('size 256')
for i in range(3):
    block(enc, [(':status', ['302', '307', '200'][i]), ('cache-control', 'private'),
                ('date', 'Mon, 21 Oct 2013 20:13:%02d GMT' % (21 + i)), ('location', 'https://www.example.com')])
# random sequences, with evictions and size changes
for seq in range(12):
    enc = Encoder()
    lines.append('reset')
    for k in range(8):
        if rng.random() < 0.15:
            size = rng.choice([0, 64, 256, 1024, 4096])
            enc.header_table_size = size
            lines.append('size %d' % size)
        hs = [(rng.choice(names), rng.choice(words)) for _ in range(rng.randint(1, 8))]
        block(enc, hs)
with open(os.path.join(root, 'std', 'net', 'hpack', 'testdata', 'cases.txt'), 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(len(lines))
