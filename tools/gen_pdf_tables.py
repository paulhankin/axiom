#!/usr/bin/env python3
# Generates std/graphics/pdf/tables.ax for std/graphics/pdf/read: the simple-font encodings
# (WinAnsi, MacRoman, Standard), PDFDocEncoding, and the Adobe Glyph List
# (glyph name to Unicode, the legacy list that old fonts use too). Needs fontTools (pip install fonttools).
import os
import subprocess
from fontTools import agl
from fontTools.encodings.StandardEncoding import StandardEncoding
from fontTools.encodings.MacRoman import MacRoman

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'graphics', 'pdf', 'tables.ax')


def by_name(names):
    out = []
    for n in names:
        out.append(agl.AGL2UV.get(n, 0) if n != '.notdef' else 0)
    return out


win = []
for c in range(256):
    try:
        u = ord(bytes([c]).decode('cp1252'))
    except UnicodeDecodeError:
        u = 0x2022 if c > 40 else 0  # PDF: unused codes above 40 show as bullets
    if c < 32:
        u = 0
    win.append(u)
win[0x7f] = 0x2022
win[0xa0] = 0x20
win[0xad] = 0x2d

mac = by_name(MacRoman)
for c in range(32, 128):
    if mac[c] == 0:
        mac[c] = c
std = by_name(StandardEncoding)

doc = list(range(256))
for c in list(range(0, 0x18)) + [0x7f]:
    if c not in (9, 10, 13):
        doc[c] = 0
doc[0x18:0x20] = [0x02d8, 0x02c7, 0x02c6, 0x02d9, 0x02dd, 0x02db, 0x02da, 0x02dc]
doc[0x80:0xa1] = [0x2022, 0x2020, 0x2021, 0x2026, 0x2014, 0x2013, 0x0192, 0x2044, 0x2039, 0x203a, 0x2212, 0x2030,
                  0x201e, 0x201c, 0x201d, 0x2018, 0x2019, 0x201a, 0x2122, 0xfb01, 0xfb02, 0x0141, 0x0152, 0x0160,
                  0x0178, 0x017d, 0x0131, 0x0142, 0x0153, 0x0161, 0x017e, 0xfffd, 0x20ac]
assert len(doc) == 256

names = sorted((n, v[0]) for n, v in agl.LEGACY_AGL2UV.items() if v[0] < 0x10000)
pool = ''.join(n for n, _ in names)
offs = [0]
for n, _ in names:
    offs.append(offs[-1] + len(n))


def arr(name, ty, xs, per=12, doc=None):
    rows = []
    for i in range(0, len(xs), per):
        rows.append('    ' + ', '.join(str(x) for x in xs[i:i + per]) + ',')
    head = ('/// %s\n' % doc) if doc else ''
    return '%spub let %s: [%d]%s = [\n%s\n];' % (head, name, len(xs), ty, '\n'.join(rows))


parts = [
    '// Generated by tools/gen_pdf_tables.py (encodings from the PDF specification,\n'
    '// glyph names from the Adobe Glyph List). Do not edit.',
    arr('WIN_ANSI', 'u16', win, doc='Code to Unicode (0: none), for each simple-font encoding'),
    arr('MAC_ROMAN', 'u16', mac),
    arr('STANDARD', 'u16', std),
    arr('PDF_DOC', 'u16', doc, doc='PDFDocEncoding, for text strings without a byte order mark'),
    'pub const GLYPH_COUNT: usize = %d;' % len(names),
    '/// Glyph names, sorted and run together: name i is\n/// GLYPH_NAMES[GLYPH_OFFSET[i]..GLYPH_OFFSET[i + 1]].\npub let GLYPH_NAMES: []u8 = "%s";' % pool,
    arr('GLYPH_OFFSET', 'u16', offs),
    arr('GLYPH_UNICODE', 'u16', [u for _, u in names]),
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as f:
    f.write('\n\n'.join(parts) + '\n')
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
exe = os.path.join(root, 'cmd/axiom/build/axiom')
if os.path.exists(exe):
    subprocess.run([exe, 'fmt', OUT], check=True)
print('%d glyph names -> %s' % (len(names), OUT))
