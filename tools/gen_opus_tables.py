#!/usr/bin/env python3
"""Generates std/audio/opus/tables.ph (CELT's mode tables, PVQ counts and
energy models; SILK's codebooks and probability tables) from libopus's
sources, as the C compiler would store them (float literals rounded to
float once).

    curl -sO https://static.crates.io/crates/audiopus_sys/audiopus_sys-0.2.2.crate
    tar xzf audiopus_sys-0.2.2.crate
    tools/gen_opus_tables.py audiopus_sys-0.2.2/opus
"""
import os
import re
import struct
import sys
from fractions import Fraction

src = sys.argv[1]
out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'audio', 'opus', 'tables.ph')

FALSE = {'FIXED_POINT', 'CUSTOM_MODES', 'ENABLE_HARDENING', 'ENABLE_ASSERTIONS', 'SMALL_FOOTPRINT', 'HAVE_ARM_NE10',
         'OVERRIDE_FFT', 'CUSTOM_MODES_ONLY'}


def unifdef(text):
    """Keeps the branches of #if(n)def/#if defined() on the macros above
    (others are kept whole)."""
    out = []
    stack = []  # (keeping, decided)
    keep = True
    for line in text.split('\n'):
        s = line.strip()
        m = re.match(r'#\s*(ifdef|ifndef|if|else|endif|elif)\b\s*(.*)', s)
        if m:
            d, arg = m.group(1), m.group(2)
            name = re.sub(r'defined\s*\(?\s*(\w+)\s*\)?', r'\1', arg).strip()
            neg = name.startswith('!')
            name = name.lstrip('!').strip()
            if d in ('ifdef', 'ifndef', 'if'):
                if name in FALSE:
                    val = (d == 'ifndef') ^ neg
                    stack.append((keep, val))
                    keep = keep and val
                else:
                    stack.append((keep, None))
                continue
            if d == 'else':
                parent, val = stack[-1]
                if val is not None:
                    keep = parent and not val
                continue
            if d == 'elif':
                continue
            if d == 'endif':
                keep = stack.pop()[0]
                continue
        if keep:
            out.append(line)
    return '\n'.join(out)


def read(path):
    t = open(os.path.join(src, path)).read()
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    t = re.sub(r'//[^\n]*', '', t)
    return unifdef(t)


def array(text, name):
    m = re.search(r'\b' + re.escape(name) + r'(\s*\[[^\]]*\])*\s*=\s*\{', text)
    if not m:
        raise SystemExit('no ' + name)
    i = m.end()
    depth = 1
    j = i
    while depth:
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
        j += 1
    body = text[i:j - 1]
    body = body.replace('{', ' ').replace('}', ' ')
    return [v.strip() for v in body.split(',') if v.strip()]


def to_f32(lit):
    """The float a C compiler stores for a decimal literal, as the
    shortest decimal string that is exactly that float as a double."""
    lit = lit.strip().rstrip('fF')
    if '/' in lit:
        a, b = lit.split('/')
        x = Fraction(a.strip()) / Fraction(b.strip().rstrip('.'))
    else:
        x = Fraction(lit)
    d = float(x)
    f = struct.unpack('f', struct.pack('f', d))[0]
    # correct any double rounding: compare with the neighbouring floats
    bits = struct.unpack('I', struct.pack('f', f))[0]
    best = f
    for nb in (bits - 1, bits + 1):
        if nb < 0 or nb >= 1 << 32:
            continue
        g = struct.unpack('f', struct.pack('I', nb))[0]
        if abs(Fraction(g) - x) < abs(Fraction(best) - x) or (
                abs(Fraction(g) - x) == abs(Fraction(best) - x) and (nb & 1) == 0):
            best = g
    return repr(best)


def ints(vals):
    return [int(re.sub(r'[uUlL]+$', '', v), 0) for v in vals]


lines = ['// Generated by tools/gen_opus_tables.py from libopus. Do not edit.', '']


def emit(name, typ, vals, doc=''):
    """A table, in phalange fmt's layout: on one line if it fits, else one
    value per line."""
    if doc:
        lines.append('/// ' + doc)
    body = ', '.join(str(v) for v in vals)
    one = 'pub let %s: [%d]%s = [%s];' % (name, len(vals), typ, body)
    if len(one) <= 120:
        lines.append(one)
    else:
        lines.append('pub let %s: [%d]%s = [' % (name, len(vals), typ))
        lines.extend('    %s,' % v for v in vals)
        lines.append('];')
    lines.append('')


# --- CELT --------------------------------------------------------------------
modes = read('celt/modes.c')
static = read('celt/static_modes_float.h')
emit('EBANDS', 'i16', ints(array(modes, 'eband5ms')), 'band edges, in units of 200 Hz at 20 ms (eband5ms)')
emit('BAND_ALLOCATION', 'u8', ints(array(modes, 'band_allocation')), '[11][21] 1/32 bit per sample')
emit('WINDOW', 'f32', [to_f32(v) for v in array(static, 'window120')])
emit('LOGN', 'i16', ints(array(static, 'logN400')))
emit('CACHE_INDEX', 'i16', ints(array(static, 'cache_index50')))
emit('CACHE_BITS', 'u8', ints(array(static, 'cache_bits50')))
emit('CACHE_CAPS', 'u8', ints(array(static, 'cache_caps50')))
emit('FFT_TWIDDLES', 'f32', [to_f32(v) for v in array(static, 'fft_twiddles48000_960')], '[480] (r, i)')
for n in (480, 240, 120, 60):
    emit('FFT_BITREV%d' % n, 'i16', ints(array(static, 'fft_bitrev%d' % n)))
emit('MDCT_TWIDDLES', 'f32', [to_f32(v) for v in array(static, 'mdct_twiddles960')])
cwrs = read('celt/cwrs.c')
emit('PVQ_U', 'u32', ints(array(cwrs, 'CELT_PVQ_U_DATA')), 'CELT_PVQ_U_DATA (rows at PVQ_U_ROW)')
rows = re.search(r'CELT_PVQ_U_ROW\[15\]\s*=\s*\{(.*?)\}', cwrs, re.S).group(1)
emit('PVQ_U_ROW', 'u32', [int(x) for x in re.findall(r'CELT_PVQ_U_DATA\s*\+\s*(\d+)', rows)])
qb = read('celt/quant_bands.c')
emit('EMEANS', 'f32', [to_f32(v) for v in array(qb, 'eMeans')])
emit('E_PROB_MODEL', 'u8', ints(array(qb, 'e_prob_model')), '[4][2][42]')

# --- SILK --------------------------------------------------------------------
TYPES = {'opus_uint8': 'u8', 'opus_int8': 'i8', 'opus_int16': 'i16', 'opus_int32': 'i32', 'unsigned char': 'u8'}
MACROS = {}
for h in ('silk/define.h', 'silk/resampler_rom.h', 'silk/pitch_est_defines.h', 'silk/tables.h'):
    for m in re.finditer(r'#\s*define\s+(\w+)\s+([^\n]+)', read(h)):
        MACROS[m.group(1)] = m.group(2).strip()


def value(v):
    for _ in range(5):
        v = re.sub(r'\b[A-Z_][A-Z0-9_]*\b', lambda m: '(' + MACROS[m.group(0)] + ')' if m.group(0) in MACROS else m.group(0), v)
    v = re.sub(r'\(\s*opus_u?int(8|16|32)\s*\)', '', v)
    v = re.sub(r'(\d)[uUlL]+\b', r'\1', v)
    return int(eval(v))


seen = set()
for f in ('tables_gain.c', 'tables_LTP.c', 'tables_NLSF_CB_NB_MB.c', 'tables_NLSF_CB_WB.c', 'tables_other.c',
          'tables_pitch_lag.c', 'tables_pulses_per_block.c', 'table_LSF_cos.c', 'pitch_est_tables.c', 'resampler_rom.c'):
    t = read('silk/' + f)
    t = re.sub(r'SILK_FIX_CONST\(\s*([^,]+?)\s*,\s*(\d+)\s*\)',
               lambda m: str(int(eval(m.group(1)) * (1 << int(m.group(2))) + 0.5)), t)
    for m in re.finditer(r'(?:static\s+)?const\s+(opus_u?int(?:8|16|32))\s+(silk_\w+)\s*(\[[^=]*\])\s*=\s*\{', t):
        typ, name = TYPES[m.group(1)], m.group(2)
        if name in seen:
            continue
        seen.add(name)
        vals = [value(v) for v in array(t, name)]
        emit(name.upper(), typ, vals)

open(out_path, 'w').write('\n'.join(lines))
print('wrote', out_path)
