#!/usr/bin/env python3
"""Generates std/net/url/testdata/cases.txt from Python's urllib.parse.

    tools/gen_url_tests.py

Each line is tab-separated, the first field saying what it checks:

    split <url> <scheme> <netloc> <path> <query> <fragment> <hostname> <port> <username> <password>
        urlsplit(url) and its accessors ("-" for None; the scheme and
        hostname as Python gives them, lowercased)
    join <base> <reference> <result>             urljoin(base, reference)
    quote <component> <input as hex> <output>    quote(input, safe=SAFE[component])
    unquote <plus> <input> <output as hex>       unquote_to_bytes, or with plus=1
                                                 unquote_plus's '+' handling
    qs <query> <pairs>                           parse_qsl(query, keep_blank_values=True):
                                                 pairs as key=value in hex, comma-separated
    urlencode <pairs> <output>                   urlencode(pairs) (pairs as for qs)

The URLs are built from random parts of the kinds RFC 3986 allows, so that
Python's lenient parser and a strict one agree on them.
"""
import os
import random
import urllib.parse as up

out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'net', 'url', 'testdata',
                        'cases.txt')
rng = random.Random(3986)

UNRESERVED = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~'
SUB_DELIMS = "!$&'()*+,;="
# the components of std/net/url's Component enum and the characters each
# leaves alone besides the unreserved ones
SAFE = {
    'component': '',
    'userinfo': SUB_DELIMS + ':',
    'host': SUB_DELIMS,
    'segment': SUB_DELIMS + ':@',
    'path': SUB_DELIMS + ':@/',
    'query': SUB_DELIMS + ':@/?',
    'fragment': SUB_DELIMS + ':@/?',
}


def pick(chars, lo, hi):
    return ''.join(rng.choice(chars) for _ in range(rng.randint(lo, hi)))


def pct():
    return '%%%02X' % rng.randrange(256) if rng.random() < 0.7 else '%%%02x' % rng.randrange(256)


def text(chars, lo, hi):
    out = ''
    for _ in range(rng.randint(lo, hi)):
        out += pct() if rng.random() < 0.1 else rng.choice(chars)
    return out


def host():
    k = rng.randrange(6)
    if k == 0:
        return '%d.%d.%d.%d' % tuple(rng.randrange(256) for _ in range(4))
    if k == 1:
        return rng.choice(['[::1]', '[2001:db8::7]', '[2001:DB8:0:0:8:800:200C:417A]', '[fe80::1:2]',
                           '[::ffff:192.0.2.1]', '[1:2:3:4:5:6:7:8]', '[::]'])
    labels = [pick('abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789', 1, 8)
              for _ in range(rng.randint(1, 4))]
    h = '.'.join(labels)
    if k == 2:
        h = 'xn--' + h  # punycode passes through
    return h


def url():
    scheme = rng.choice(['http', 'https', 'HTTP', 'Https', 'ws', 'wss', 'file', 'ftp', 'git+ssh', 'x-y.z'])
    s = scheme + ':'
    if rng.random() < 0.9:
        s += '//'
        if rng.random() < 0.2:
            s += text(UNRESERVED + SUB_DELIMS.replace(':', ''), 1, 6)
            if rng.random() < 0.6:
                s += ':' + text(UNRESERVED + SUB_DELIMS + ':', 0, 6)
            s += '@'
        s += host()
        if rng.random() < 0.3:
            s += ':' + str(rng.choice([80, 443, 8080, 1, 65535, 21, rng.randrange(65536)]))
        segs = [text(UNRESERVED + SUB_DELIMS + ':@', 0, 6) for _ in range(rng.randint(0, 4))]
        if segs:
            s += '/' + '/'.join(segs)
    else:
        s += text(UNRESERVED + SUB_DELIMS + '@', 1, 6) + '/' + text(UNRESERVED + SUB_DELIMS + ':@', 0, 6)
    if rng.random() < 0.4:
        s += '?' + text(UNRESERVED + SUB_DELIMS + ':@/?', 1, 12)
    if rng.random() < 0.3:
        s += '#' + text(UNRESERVED + SUB_DELIMS + ':@/?', 1, 8)
    return s


def opt(v):
    return '-' if v is None else str(v)


lines = ["# generated by tools/gen_url_tests.py from Python's urllib.parse; do not edit"]
for _ in range(400):
    u = url()
    p = up.urlsplit(u)
    lines.append('\t'.join(['split', u, p.scheme, p.netloc, p.path, p.query, p.fragment, opt(p.hostname),
                            opt(p.port), opt(p.username), opt(p.password)]))

bases = ['http://a/b/c/d;p?q', 'https://example.com', 'http://u@h:8/x/y/', 'http://a/b/c/d;p?q#f', 'ws://h/a/b?c']
for _ in range(400):
    base = rng.choice(bases)
    # (no empty segments: Python's urljoin drops them, which RFC 3986 does not)
    parts = [rng.choice(['..', '.', 'g', 'g;x', 'h%41', 'k=1', '..', '.']) for _ in range(rng.randint(1, 5))]
    ref = '/'.join(parts)
    r = rng.random()
    if r < 0.2:
        ref = '/' + ref
    elif r < 0.25:
        # (Python leaves dot segments in a reference with an authority)
        ref = '//g/' + '/'.join(p for p in parts if p not in ('.', '..'))
    elif r < 0.3:
        ref = ''
    if rng.random() < 0.25:
        ref += '?y=' + pick('abc/.', 0, 3)
    if rng.random() < 0.2:
        ref += '#' + pick('abc/?', 1, 3)  # (Python drops an empty fragment)
    if ref == '' and '#' in base:
        continue  # (Python keeps the base's fragment, which RFC 3986 drops)
    lines.append('\t'.join(['join', base, ref, up.urljoin(base, ref)]))

for comp, safe in SAFE.items():
    for _ in range(25):
        s = bytes(rng.randrange(256) if rng.random() < 0.3 else ord(rng.choice(UNRESERVED + SUB_DELIMS + ':@/?#[]% '))
                  for _ in range(rng.randint(0, 20)))
        lines.append('\t'.join(['quote', comp, s.hex(), up.quote(s, safe=safe)]))

for _ in range(60):
    s = text(UNRESERVED + SUB_DELIMS + ':@/?', 0, 15)
    plus = rng.randrange(2)
    out = up.unquote_to_bytes(s.replace('+', ' ') if plus else s)
    lines.append('\t'.join(['unquote', str(plus), s, out.hex()]))


def hexpairs(pairs, encoding='utf-8'):
    return ','.join(k.encode(encoding).hex() + '=' + v.encode(encoding).hex() for k, v in pairs)


for _ in range(60):
    q = '&'.join(text('abcxyz019-._~!$\'()*,;:@/?+=', 0, 5) for _ in range(rng.randint(0, 5)))
    # (decoded as Latin-1, the bytes are the escapes' bytes)
    pairs = up.parse_qsl(q, keep_blank_values=True, encoding='latin-1')
    lines.append('\t'.join(['qs', q, hexpairs(pairs, 'latin-1')]))

for _ in range(40):
    pairs = [(pick(UNRESERVED + ' &=+%/?#é', 0, 6), pick(UNRESERVED + ' &=+%/?#é', 0, 8))
             for _ in range(rng.randint(1, 4))]
    lines.append('\t'.join(['urlencode', hexpairs(pairs), up.urlencode(pairs)]))

with open(out_path, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote %d lines to %s' % (len(lines), out_path))
