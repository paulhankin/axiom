#!/usr/bin/env python3
"""Generates std/hyphen/en_us.ph, the American English hyphenation patterns
and exceptions of the hyph-utf8 package (TeX's ushyphmax: Knuth's patterns
with Gerard D.C. Kuiken's additions), and std/hyphen/testdata/words.txt,
words from the CommonMark specification hyphenated by a reference
implementation of Liang's algorithm.

    P=https://raw.githubusercontent.com/hyphenation/tex-hyphen/master/hyph-utf8/tex/generic/hyph-utf8/patterns/txt
    curl -O $P/hyph-en-us.pat.txt -O $P/hyph-en-us.hyp.txt
    tools/gen_hyphen.py hyph-en-us.pat.txt hyph-en-us.hyp.txt
"""
import os
import re
import subprocess
import sys

pats = open(sys.argv[1]).read().split()
exc = open(sys.argv[2]).read().split()
assert len(pats) == 4938 and len(exc) == 14, (len(pats), len(exc))
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

NOTICE = '''// Hyphenation patterns for American English, from the hyph-utf8 package
// (hyph-en-us, version 2005-05-30: Knuth's hyphen.tex with the additions of
// ushyphmax.tex). See http://www.hyphenation.org/tex for more information.
//
// Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken
//
// Copying and distribution of this file, with or without modification,
// are permitted in any medium without royalty provided the copyright
// notice and this notice are preserved.
//
// Generated by tools/gen_hyphen.py. Do not edit.
'''


def lines(words, per):
    out = []
    cur = ''
    for w in words:
        if len(cur) + len(w) + 1 > per:
            out.append(cur)
            cur = ''
        cur += w + ' '
    out.append(cur)
    return out


with open(os.path.join(root, 'std', 'hyphen', 'en_us.ph'), 'w') as f:
    f.write(NOTICE + '\n')
    f.write('/// The %d patterns, separated by spaces.\n' % len(pats))
    f.write('pub let PATTERNS: []u8 = "%s";\n\n' % ' '.join(pats))
    f.write('/// The exceptions: words with their hyphens.\n')
    f.write('pub let EXCEPTIONS: []u8 = "%s";\n\n' % ' '.join(exc))
    f.write('/// The fewest letters to leave before and after a hyphen.\n')
    f.write('pub const LEFT_MIN: usize = 2;\npub const RIGHT_MIN: usize = 3;\n')
exe = os.path.join(root, 'selfhost', 'build', 'phalange')
if os.path.exists(exe):
    subprocess.run([exe, 'fmt', os.path.join(root, 'std', 'hyphen', 'en_us.ph')], check=False)

# the reference implementation
tree = {}
for p in pats:
    letters = re.sub(r'\d', '', p)
    digits = [0] * (len(letters) + 1)
    k = 0
    for c in p:
        if c.isdigit():
            digits[k] = int(c)
        else:
            k += 1
    tree[letters] = digits
maxlen = max(len(k) for k in tree)
excs = {e.replace('-', ''): e for e in exc}


def hyphenate(word):
    w = word.lower()
    if w in excs:
        return excs[w]
    work = '.' + w + '.'
    points = [0] * (len(work) + 1)
    for i in range(len(work)):
        for j in range(i + 1, min(len(work), i + maxlen) + 1):
            d = tree.get(work[i:j])
            if d:
                for k, v in enumerate(d):
                    points[i + k] = max(points[i + k], v)
    out = ''
    for k, c in enumerate(word):
        # a hyphen before letter k: points[k + 1]
        if 2 <= k <= len(word) - 3 and points[k + 1] % 2 == 1:
            out += '-'
        out += c
    return out


text = open(os.path.join(root, 'std', 'markdown', 'testdata', 'commonmark-0.31.2.txt')).read()
words = sorted(set(w for w in re.findall(r'[A-Za-z]+', text) if len(w) >= 3))
words += ['hyphenation', 'supercalifragilisticexpialidocious', 'associate', 'present', 'table', 'Hyphenation']
os.makedirs(os.path.join(root, 'std', 'hyphen', 'testdata'), exist_ok=True)
with open(os.path.join(root, 'std', 'hyphen', 'testdata', 'words.txt'), 'w') as f:
    for w in words:
        f.write(hyphenate(w) + '\n')
print(len(pats), len(exc), len(words), hyphenate('hyphenation'), hyphenate('supercalifragilisticexpialidocious'))
