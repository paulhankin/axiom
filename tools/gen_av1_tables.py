#!/usr/bin/env python3
"""Generates std/image/av1/cdf.ph (the AV1 default CDFs, the spec's tables as
dav1d holds them) and std/image/av1/tables.ph (scan orders, quantizer
matrices, dequantization and intra/CDEF/restoration tables) from the rav1d
crate's sources.

    curl -sO https://static.crates.io/crates/rav1d/rav1d-1.1.0.crate
    tar xzf rav1d-1.1.0.crate
    tools/gen_av1_tables.py rav1d-1.1.0/src

Each CDF of n symbols is stored as dav1d stores it: n - 1 values of
32768 - p, then an adaptation counter, padded to the table's stride.
"""
import ast
import os
import re
import sys

src = open(os.path.join(sys.argv[1], 'cdf.rs')).read()
body = src[src.index('static default_cdf: CdfDefaultContext'):]
body = body[:body.index('\n};\n') + 3]


def value_text(text, start):
    # the expression after "name: " up to the comma ending it at depth 0
    depth = 0
    i = start
    while True:
        c = text[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            if depth == 0:
                return text[start:i]
            depth -= 1
        elif c == ',' and depth == 0:
            return text[start:i]
        i += 1


def fields(text):
    # top-level "name: value" pairs of a struct literal's body
    out = []
    depth = 0
    i = 0
    while i < len(text):
        c = text[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif depth == 0:
            m = re.match(r'\s*(r#)?([a-z_0-9]+):\s', text[i:])
            if m and (i == 0 or text[i - 1] in ' \n,{'):
                v = value_text(text, i + m.end())
                out.append((m.group(2), v))
                i += m.end() + len(v)
                continue
        i += 1
    return out


def literal(v):
    t = re.sub(r'\b[A-Za-z_][A-Za-z_0-9]*\b', '', v)
    t = t.replace('(', '').replace(')', '')
    t = re.sub(r'\[(\d+);\s*(\d+)\]', lambda m: '[' + ', '.join([m.group(1)] * int(m.group(2))) + ']', t)
    return ast.literal_eval(t.strip())


def inner(struct_text):
    return struct_text[struct_text.index('{') + 1:struct_text.rindex('}')]


top = inner(body)
tables = {}
for name, v in fields(top):
    if name == 'coef':
        arr = v[v.index('[') + 1:v.rindex(']')]
        parts = [p for p in re.split(r'CdfCoefContext\s*', arr) if '{' in p]
        for q, p in enumerate(parts):
            for fname, fv in fields(inner(p)):
                tables.setdefault('coef_' + fname, []).append(literal(fv))
    elif name in ('m', 'mi'):
        for fname, fv in fields(inner(v)):
            tables[fname] = literal(fv)
    elif name == 'mv':
        for fname, fv in fields(inner(v)):
            if fname == 'comp':
                for cname, cv in fields(inner(fv)):
                    tables['mv_' + cname] = literal(cv)
            else:
                tables['mv_' + fname] = literal(fv)
    else:
        tables[name] = literal(v)

WANT = ['coef_eob_bin_16', 'coef_eob_bin_32', 'coef_eob_bin_64', 'coef_eob_bin_128', 'coef_eob_bin_256',
        'coef_eob_bin_512', 'coef_eob_bin_1024', 'coef_eob_base_tok', 'coef_base_tok', 'coef_br_tok',
        'coef_eob_hi_bit', 'coef_skip', 'coef_dc_sign', 'kfym', 'uv_mode', 'partition', 'cfl_alpha', 'txtp_intra1',
        'txtp_intra2', 'cfl_sign', 'angle_delta', 'filter_intra', 'seg_id', 'pal_sz', 'color_map', 'txsz', 'delta_q',
        'delta_lf', 'restore_switchable', 'restore_wiener', 'restore_sgrproj', 'use_filter_intra', 'skip', 'pal_y',
        'pal_uv', 'intrabc', 'mv_joint', 'mv_classes', 'mv_sign', 'mv_class_0', 'mv_class_0_fp', 'mv_class_0_hp',
        'mv_class_n_fp', 'mv_class_n_hp', 'mv_class_n']


def cdfs(x):
    # the innermost lists (one per CDF), in order, and the dimensions above
    if all(isinstance(e, int) for e in x):
        return [x], []
    out = []
    dims = None
    for e in x:
        c, d = cdfs(e)
        out += c
        dims = d
    return out, [len(x)] + dims


lines = ['// Generated by tools/gen_av1_tables.py from rav1d\'s src/cdf.rs: the AV1',
         '// default CDFs. Do not edit.', '//',
         '// A CDF of n symbols is n - 1 values of 32768 - p, then a counter, in',
         '// STRIDE slots; tables are laid out row-major over their dimensions.', '']
mode_parts = []
coef_parts = [[] for _ in range(4)]
mode_off = 0
coef_off = 0
for name in WANT:
    t = tables[name]
    if name.startswith('coef_'):
        per_q = [cdfs(t[q]) for q in range(4)]
        cl, dims = per_q[0]
    else:
        cl, dims = cdfs(t)
    stride = max(len(c) for c in cl) + 1
    up = name.upper()
    lines.append('/// %s: [%s] of %d slots' % (name, ']['.join(map(str, dims)) or '1', stride))
    lines.append('pub const %s_STRIDE: usize = %d;' % (up, stride))
    if name.startswith('coef_'):
        lines.append('pub const %s: usize = %d;' % (up, coef_off))
        for q in range(4):
            for c in per_q[q][0]:
                coef_parts[q] += [(32768 - p) & 32767 for p in c] + [0] * (stride - len(c))
        coef_off += len(cl) * stride
    else:
        lines.append('pub const %s: usize = %d;' % (up, mode_off))
        for c in cl:
            mode_parts += [(32768 - p) & 32767 for p in c] + [0] * (stride - len(c))
        mode_off += len(cl) * stride
    lines.append('')


def arr(name, v):
    s = 'pub let %s: [%d]u16 = [' % (name, len(v))
    return s + ', '.join(map(str, v)) + '];'


lines.append('/// The coefficient CDFs of one quantizer context, and all four')
lines.append('pub const COEF_SIZE: usize = %d;' % coef_off)
lines.append(arr('COEF_DEFAULTS', sum(coef_parts, [])))
lines.append('')
lines.append('/// Every other CDF')
lines.append('pub const MODE_SIZE: usize = %d;' % mode_off)
lines.append(arr('MODE_DEFAULTS', mode_parts))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'image', 'av1', 'cdf.ph')
open(out, 'w').write('\n'.join(lines) + '\n')
print(coef_off, mode_off)


