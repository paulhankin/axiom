def static_numbers(fname, name):
    text = open(os.path.join(sys.argv[1], fname)).read()
    i = text.index(name)
    i = text.index('=', i)
    depth = 0
    j = i
    started = False
    while True:
        c = text[j]
        if c in '([{':
            depth += 1
            started = True
        elif c in ')]}':
            depth -= 1
        elif c == ';' and depth == 0 and started:
            break
        j += 1
    body = re.sub(r'//[^\n]*', '', text[i + 1:j])
    body = re.sub(r'\b[A-Za-z_][A-Za-z_0-9]*\b', ' ', body)
    return [int(x) for x in re.findall(r'-?\b\d+\b', body)]


out = ['// Generated by tools/gen_av1_tables.py from rav1d\'s sources: AV1 scan',
       '// orders, quantizer matrices, dequantization and filter tables. Do not edit.', '']
scan_names = ['scan_4x4', 'scan_8x8', 'scan_16x16', 'scan_32x32', 'scan_4x8', 'scan_8x4', 'scan_8x16',
              'scan_16x8', 'scan_16x32', 'scan_32x16', 'scan_4x16', 'scan_16x4', 'scan_8x32', 'scan_32x8']
scans = {}
data = []
for n in scan_names:
    v = static_numbers('scan.rs', 'static ' + n + ':')
    w, h = map(int, n[5:].split('x'))
    v = v[-(w * h):]
    scans[n] = len(data)
    data += v
order = ['scan_4x4', 'scan_8x8', 'scan_16x16', 'scan_32x32', 'scan_32x32', 'scan_4x8', 'scan_8x4', 'scan_8x16',
         'scan_16x8', 'scan_16x32', 'scan_32x16', 'scan_32x32', 'scan_32x32', 'scan_4x16', 'scan_16x4',
         'scan_8x32', 'scan_32x8', 'scan_16x32', 'scan_32x16']
out.append('/// The scan order of each transform size (TxfmSize order), at SCAN_OFF[tx]')
out.append(arr('SCANS', data).replace(']u16', ']u16'))
out.append('pub let SCAN_OFF: [19]u32 = [%s];' % ', '.join(str(scans[n]) for n in order))
out.append('')
qm16 = static_numbers('qm.rs', 'static qm_tbl_32x16:')
qm16 = qm16[-(15 * 2 * 512):]
qm32 = static_numbers('qm.rs', 'static qm_tbl_32x32_t:')
qm32 = qm32[-(15 * 2 * 528):]
out.append('/// Quantizer matrices [level][chroma]: 32x16, and 32x32 as a triangle')
out.append('pub let QM_32X16: [%d]u8 = [%s];' % (len(qm16), ', '.join(map(str, qm16))))
out.append('pub let QM_32X32_T: [%d]u8 = [%s];' % (len(qm32), ', '.join(map(str, qm32))))
out.append('')
dq = static_numbers('dequant_tables.rs', 'pub static dav1d_dq_tbl:')
dq = dq[-(3 * 256 * 2):]
out.append('/// [bit depth 8, 10, 12][qindex][dc, ac]')
out.append(arr('DQ_TBL', dq))
for nm, cnt, ty, key in [('SM_WEIGHTS', 128, 'u8', 'pub static dav1d_sm_weights:'),
                         ('DR_INTRA_DERIVATIVE', 44, 'u16', 'pub static dav1d_dr_intra_derivative:'),
                         ('SGR_X_BY_X', 256, 'u8', 'pub static dav1d_sgr_x_by_x:')]:
    v = static_numbers('tables.rs', key)[-cnt:]
    out.append('pub let %s: [%d]%s = [%s];' % (nm, cnt, ty, ', '.join(map(str, v))))
v = static_numbers('tables.rs', 'pub static dav1d_sgr_params:')[-32:]
out.append('pub let SGR_PARAMS: [32]u16 = [%s];' % ', '.join(map(str, v)))
text = open(os.path.join(sys.argv[1], 'tables.rs')).read()
i = text.index('pub static dav1d_cdef_directions')
i = text.index('= [', i)
j = text.index('];', i)
v = []
for pair in re.findall(r'\[([^\[\]]+)\]', text[i + 2:j]):
    for e in pair.split(','):
        off = eval(e)
        dy = (off + 6) // 12
        v += [dy, off - 12 * dy]
out.append('/// [direction][tap][dy, dx]')
out.append('pub let CDEF_DIRECTIONS: [48]i32 = [%s];' % ', '.join(map(str, v)))
text = open(os.path.join(sys.argv[1], 'tables.rs')).read()
i = text.index('pub static dav1d_filter_intra_taps')
j = text.index('];', i)
taps = [int(x) for x in re.findall(r'-?\d+', re.sub(r'Align64<\[i8; 64\]>; 5', '', text[i:j]))]
taps = taps[-(5 * 8 * 7):]
out.append('/// [mode][output position][7 taps]')
out.append('pub let FILTER_INTRA_TAPS: [280]i32 = [%s];' % ', '.join(map(str, taps)))
out2 = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'image', 'av1', 'tables.ph')
open(out2, 'w').write('\n'.join(out) + '\n')
print('tables', len(data), len(qm16), len(qm32), len(dq), len(taps))
