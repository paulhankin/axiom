#!/usr/bin/env python3
"""Generates std/audio/aac/tables.ph (scalefactor band layouts, the Huffman
codebooks, dequantisation values, TNS and LTP coefficients and the sine and
KBD windows) from FFmpeg's AAC decoder, as FFmpeg computes them.

    for f in aactab.c aactab.h; do
        curl -sO https://raw.githubusercontent.com/FFmpeg/FFmpeg/n6.1.1/libavcodec/$f
    done
    tools/gen_aac_tables.py .

The KBD windows use FFmpeg's own Bessel function (av_bessel_i0, from
libavutil through ctypes).
"""
import ctypes
import ctypes.util
import math
import os
import re
import struct
import sys

src = sys.argv[1]
out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'audio', 'aac', 'tables.ph')


def read(path):
    t = open(os.path.join(src, path)).read()
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    return re.sub(r'//[^\n]*', '', t)


def array(text, name):
    m = re.search(r'\b' + re.escape(name) + r'\s*(\)\s*)?(\[[^\]]*\])*\s*=\s*\{', text)
    if not m:
        raise SystemExit('no ' + name)
    i = m.end()
    depth = 1
    j = i
    while depth:
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
        j += 1
    body = text[i:j - 1].replace('{', ' ').replace('}', ' ')
    return [v.strip() for v in body.split(',') if v.strip()]


def f32(x):
    """The shortest decimal that reads back as the float nearest x."""
    f = struct.unpack('f', struct.pack('f', x))[0]
    for digits in range(6, 12):
        s = '%.*g' % (digits, f)
        if struct.unpack('f', struct.pack('f', float(s)))[0] == f:
            break
    if 'e' not in s and '.' not in s:
        s += '.0'
    return s


def lit(v):
    v = re.sub(r'^Q3[01]\((.*)\)$', r'\1', v.strip()).rstrip('fF')
    return f32(float(v))


def ints(vals):
    return [int(re.sub(r'[uUlL]+$', '', v), 0) for v in vals]


lines = ['// Generated by tools/gen_aac_tables.py from FFmpeg (libavcodec/aactab.c). Do not edit.', '']


def emit(name, typ, vals, doc=''):
    if doc:
        lines.append('/// ' + doc)
    lines.append('pub let %s: [%d]%s = [%s];' % (name, len(vals), typ, ', '.join(str(v) for v in vals)))
    lines.append('')


tab = read('aactab.c')
hdr = read('aactab.h')

emit('NUM_SWB_1024', 'u8', ints(array(tab, 'ff_aac_num_swb_1024')), 'scalefactor bands by sampling index')
emit('NUM_SWB_128', 'u8', ints(array(tab, 'ff_aac_num_swb_128')))
emit('PRED_SFB_MAX', 'u8', ints(array(tab, 'ff_aac_pred_sfb_max')))
emit('TNS_MAX_BANDS_1024', 'u8', ints(array(tab, 'ff_tns_max_bands_1024')))
emit('TNS_MAX_BANDS_128', 'u8', ints(array(tab, 'ff_tns_max_bands_128')))

for n in ('1024', '128'):
    names = array(tab, 'ff_swb_offset_' + n)
    data = []
    start = {}
    starts = []
    for nm in names:
        if nm not in start:
            start[nm] = len(data)
            data += ints(array(tab, nm))
        starts.append(start[nm])
    emit('SWB_OFFSET_%s' % n, 'u16', data, 'band offsets, the layouts one after another')
    emit('SWB_OFFSET_%s_START' % n, 'u16', starts, 'where each sampling index\'s layout starts')

emit('SF_CODE', 'u32', ints(array(tab, 'ff_aac_scalefactor_code')), 'scalefactor Huffman code (index 60 = difference 0)')
emit('SF_BITS', 'u8', ints(array(tab, 'ff_aac_scalefactor_bits')))
codes = []
bits = []
starts = []
for k in range(1, 12):
    starts.append(len(codes))
    c = ints(array(tab, 'codes%d' % k))
    b = ints(array(tab, 'bits%d' % k))
    assert len(c) == len(b)
    codes += c
    bits += b
starts.append(len(codes))
emit('SPECTRAL_CODES', 'u16', codes, 'the spectral codebooks 1-11, one after another')
emit('SPECTRAL_BITS', 'u8', bits)
emit('SPECTRAL_START', 'u16', starts)
emit('VALS', 'f32', [lit(v) for v in array(tab, 'codebook_vector10_vals')], 'i^(4/3) for 0 <= i < 16, as FFmpeg rounds them')

tns = []
for nm in ('tns_tmp2_map_0_3', 'tns_tmp2_map_0_4', 'tns_tmp2_map_1_3', 'tns_tmp2_map_1_4'):
    tns += [lit(v) for v in array(hdr, nm)]
emit('TNS_COEF', 'f32', tns, 'TNS coefficients: [0_3] at 0, [0_4] at 8, [1_3] at 24, [1_4] at 28 (compress_res)')
emit('LTP_COEF', 'f32', [lit(v) for v in array(hdr, 'ltp_coef')])


def sine(n):
    out = []
    for i in range(n):
        x = struct.unpack('f', struct.pack('f', (i + 0.5) * (math.pi / (2.0 * n))))[0]
        out.append(f32(math.sin(x)))
    return out


avutil = ctypes.CDLL(ctypes.util.find_library('avutil'))
avutil.av_bessel_i0.restype = ctypes.c_double
avutil.av_bessel_i0.argtypes = [ctypes.c_double]


def kbd(alpha, n):
    alpha = struct.unpack('f', struct.pack('f', alpha))[0]
    alpha2 = 4 * (alpha * math.pi / n) * (alpha * math.pi / n)
    temp = []
    scale = 0.0
    for i in range(n // 2 + 1):
        tmp = alpha2 * i * (n - i)
        temp.append(avutil.av_bessel_i0(math.sqrt(tmp)))
        scale += temp[i] * (1 + (1 if (i and i < n // 2) else 0))
    scale = 1.0 / (scale + 1)
    out = []
    s = 0.0
    for i in range(n // 2 + 1):
        s += temp[i]
        out.append(f32(math.sqrt(s * scale)))
    for i in range(n // 2 + 1, n):
        s += temp[n - i]
        out.append(f32(math.sqrt(s * scale)))
    return out


emit('SINE_1024', 'f32', sine(1024), 'the rising halves of the windows')
emit('SINE_128', 'f32', sine(128))
emit('KBD_1024', 'f32', kbd(4.0, 1024))
emit('KBD_128', 'f32', kbd(6.0, 128))

os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, 'w') as f:
    f.write('\n'.join(lines))
print('wrote', out_path)
