def filters(proto, bands):
    out = []
    for q in range(bands):
        for n in range(8):
            if n == 7:
                out += [0.0, 0.0]
                continue
            th = 2 * math.pi * (q + 0.5) * (n - 6) / bands
            out += [F(F(proto[n]) * libm.cos(th)), F(F(proto[n]) * -libm.sin(th))]
    return [f32(v) for v in out]


