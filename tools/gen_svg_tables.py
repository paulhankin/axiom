#!/usr/bin/env python3
"""Generates std/graphics/svg/colors.ph: the colour keywords of SVG 1.1
(section 4.4, the same as CSS Color Module Level 3's extended keywords),
plus CSS's "rebeccapurple", from Pillow's table of them (PIL.ImageColor)."""
import os

from PIL import ImageColor

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'graphics', 'svg', 'colors.ph')
names = sorted(ImageColor.colormap.items())
lines = [
    '// =============================================================================',
    '// std/graphics/svg/colors.ph - the colour keywords of SVG 1.1 and CSS 3 (sorted).',
    '// Generated by tools/gen_svg_tables.py from Pillow\'s ImageColor table. Do not edit.',
    '// =============================================================================',
    '',
    '/// A colour keyword and its sRGB value (0xrrggbb).',
    'pub struct Named {',
    '    name: []u8,',
    '    rgb: u32,',
    '}',
    '',
    '/// The keywords, sorted by name.',
    'pub let NAMES: [%d]Named = [' % len(names),
]
for name, value in names:
    assert value.startswith('#') and len(value) == 7
    lines.append('    Named.{ name: "%s", rgb: 0x%s },' % (name, value[1:]))
lines.append('];')
with open(out, 'w') as f:
    f.write('\n'.join(lines) + '\n')
