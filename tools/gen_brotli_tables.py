#!/usr/bin/env python3
"""Generates std/brotli/tables.ph: the static dictionary (RFC 7932 Appendix
A) and the word transforms (Appendix B), from the brotli sources.

    curl -O https://raw.githubusercontent.com/google/brotli/master/c/common/dictionary.bin
    curl -O https://raw.githubusercontent.com/google/brotli/master/c/common/transform.c
    curl -O https://raw.githubusercontent.com/google/brotli/master/c/common/context.c
    tools/gen_brotli_tables.py dictionary.bin transform.c context.c
"""
import ast
import hashlib
import os
import re
import subprocess
import sys

dic = open(sys.argv[1], 'rb').read()
assert hashlib.sha256(dic).hexdigest() == '20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70'
src = open(sys.argv[2]).read()
ctx_src = re.sub(r'/\*.*?\*/', '', open(sys.argv[3]).read(), flags=re.S)
lut = [int(x) for x in re.findall(r'\d+', re.search(r'\[2048\] = \{(.*?)\};', ctx_src, re.S).group(1))]
assert len(lut) == 2048

# the prefix and suffix strings: C string literals run together
m = re.search(r'kPrefixSuffix\[\d+\] =(.*?);', src, re.S)
lits = re.findall(r'"((?:[^"\\]|\\.)*)"', re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S))
ps = b''
for lit in lits:
    # C octal and hex escapes, as Python bytes literals read them
    ps += ast.literal_eval('b"' + lit + '"')
ps += b'\0'
mp = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', re.search(r'kPrefixSuffixMap\[50\] = \{(.*?)\}', src, re.S).group(1))]
assert len(mp) == 50
names = {'IDENTITY': 0, 'UPPERCASE_FIRST': 10, 'UPPERCASE_ALL': 11}
for k in range(1, 10):
    names['OMIT_LAST_%d' % k] = k
    names['OMIT_FIRST_%d' % k] = 11 + k
body = re.search(r'kTransformsData\[\] = \{(.*?)\};', src, re.S).group(1)
triples = re.findall(r'(\d+),\s*BROTLI_TRANSFORM_(\w+),\s*(\d+)', body)
assert len(triples) == 121
tr = []
for a, t, b in triples:
    tr += [int(a), names[t], int(b)]


def esc(b):
    out = []
    for c in b:
        if c == 0x22:
            out.append('\\"')
        elif c == 0x5c:
            out.append('\\\\')
        elif 0x20 <= c < 0x7f:
            out.append(chr(c))
        else:
            out.append('\\x%02x' % c)
    return ''.join(out)


def string(name, b):
    lines = []
    for i in range(0, len(b), 96):
        lines.append('    "%s"' % esc(b[i:i + 96]))
    return 'pub let %s: []u8 =\n%s;' % (name, ' ++\n'.join(lines)) if False else \
        'pub let %s: []u8 = "%s";' % (name, esc(b))


def arr(name, ty, xs, per=16):
    rows = ['    ' + ', '.join(str(x) for x in xs[i:i + per]) + ',' for i in range(0, len(xs), per)]
    return 'pub let %s: [%d]%s = [\n%s\n];' % (name, len(xs), ty, '\n'.join(rows))


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'std', 'brotli', 'tables.ph')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('// Generated by tools/gen_brotli_tables.py: the static dictionary and word\n'
            '// transforms of RFC 7932 (appendices A and B). Do not edit.\n\n')
    f.write('/// The 122,784-byte dictionary.\n' + string('DICTIONARY', dic) + '\n\n')
    f.write('/// Prefixes and suffixes, each a length byte and then its bytes; PS_OFFSET\n'
            '/// gives where each starts.\n' + string('PREFIX_SUFFIX', ps) + '\n\n')
    f.write(arr('PS_OFFSET', 'u16', mp) + '\n\n')
    f.write('/// For each of the 121 transforms: prefix, type (0 identity, 1-9 omit the\n'
            '/// last k, 10 uppercase the first, 11 uppercase all, 12-20 omit the first\n'
            '/// k - 11), suffix.\n' + arr('TRANSFORMS', 'u8', tr, 15) + '\n\n')
    f.write('/// Literal context lookup (section 7.1): for context mode m, the context\n'
            '/// of bytes p1, p2 is LUT[m * 512 + p1] | LUT[m * 512 + 256 + p2].\n' +
            arr('CONTEXT_LUT', 'u8', lut, 16) + '\n')
exe = os.path.join(os.path.dirname(out), '..', '..', 'selfhost', 'build', 'phalange')
if os.path.exists(exe):
    subprocess.run([exe, 'fmt', out], check=False)
print(out, len(dic), len(ps), len(tr) // 3)
