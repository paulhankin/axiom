/* (the wide string's first characters below 128, narrowed; NULL if no memory) */
static char *narrow(const wchar_t *w, size_t *len)
{
    size_t n = 0, i;
    char *s;
    while (w[n] != 0 && (unsigned long)w[n] < 128)
        n++;
    s = (char *)malloc(n + 1);
    if (s == NULL)
        return NULL;
    for (i = 0; i < n; i++)
        s[i] = (char)w[i];
    s[n] = 0;
    *len = n;
    return s;
}

_Float16 wcstof16(const wchar_t *restrict __n, wchar_t **restrict __e)
{
    size_t len;
    char *end, *s = narrow(__n, &len);
    _Float16 r;
    if (s == NULL) {
        if (__e != NULL)
            *__e = (wchar_t *)__n;
        return 0;
    }
    r = strtof16(s, &end);
    if (__e != NULL)
        *__e = (wchar_t *)__n + (end - s);
    free(s);
    return r;
}

