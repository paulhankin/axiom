#!/usr/bin/env python3
# Generates std/text/html/entities.ax: the HTML5 named character references
# (from Python's html.entities.html5, the WHATWG list), for std/text/html and
# std/text/markdown.
import html.entities
import os
import subprocess

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'std', 'text', 'internal', 'html', 'entities.ax')
ents = sorted((k[:-1], v) for k, v in html.entities.html5.items() if k.endswith(';'))
names = ''.join(k for k, _ in ents)
offs = [0]
for k, _ in ents:
    offs.append(offs[-1] + len(k))


def arr(name, ty, xs, per=12):
    rows = []
    for i in range(0, len(xs), per):
        rows.append('    ' + ', '.join(str(x) for x in xs[i:i + per]) + ',')
    return 'pub let %s: [%d]%s = [\n%s\n];' % (name, len(xs), ty, '\n'.join(rows))


parts = [
    '// Generated by cmd/internal/tools/gen_entities.py from the WHATWG list of named character\n'
    '// references (HTML5). Do not edit.',
    'pub const COUNT: usize = %d;' % len(ents),
    '/// The names, without & and ;, sorted and run together; name i is\n'
    '/// NAMES[OFFSET[i]..OFFSET[i + 1]].\npub let NAMES: []u8 = "%s";' % names,
    arr('OFFSET', 'u16', offs),
    '/// The code points each name stands for (a second one, or 0).',
    arr('FIRST', 'u32', [ord(v[0]) for _, v in ents]),
    arr('SECOND', 'u32', [ord(v[1]) if len(v) > 1 else 0 for _, v in ents]),
    '/// The names that may also appear without a semicolon (in legacy\n/// content), as sorted indexes.',
    arr('LEGACY', 'u16', [i for i, (k, _) in enumerate(ents) if k in html.entities.html5]),
]
with open(OUT, 'w') as f:
    f.write('\n\n'.join(parts) + '\n')
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
exe = os.path.join(root, 'cmd/axiom/build/axiom')
if os.path.exists(exe):
    subprocess.run([exe, 'fmt', OUT], check=True)
print('%d entities -> %s' % (len(ents), OUT))
