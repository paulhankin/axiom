#!/usr/bin/env python3
"""Generates std/math/rational/testdata/cases.txt: operations on fractions
with the results Python's fractions module gives.

Each line is: op a b result (a and b are strings Fraction() accepts)
  add sub mul div  str(a op b)
  pow              str(a ** b), b an integer
  cmp              -1, 0 or 1
  floor ceil round math.floor(a), math.ceil(a), round(a) (b unused)
  parse            str(Fraction(a)) (b unused)
  float            the bits of float(a) in hex (b unused)
  from_float       str(Fraction(x)) for the double whose bits are b (hex)
  limit            str(a.limit_denominator(b))
"""
import math
import os
import random
import struct
from fractions import Fraction

rng = random.Random(1234)


def bigint():
    k = rng.choice([1, 1, 2, 3, 5, 10, 20, 40])
    return int(''.join(rng.choice('0123456789') for _ in range(k)))


def frac():
    kind = rng.random()
    if kind < 0.1:
        return Fraction(rng.randint(-10, 10))
    n = bigint() * rng.choice([1, -1])
    d = bigint() or 1
    if rng.random() < 0.2:
        d = 2 ** rng.randint(0, 80)
    return Fraction(n, d)


def s(f):
    return str(f)


def bits(x):
    return '%016x' % struct.unpack('<Q', struct.pack('<d', x))[0]


def decimal_string():
    sign = rng.choice(['', '-', '+'])
    ip = ''.join(rng.choice('0123456789') for _ in range(rng.randint(0, 6)))
    fp = ''.join(rng.choice('0123456789') for _ in range(rng.randint(0, 8)))
    if not ip and not fp:
        ip = '7'
    t = sign + ip
    if fp or rng.random() < 0.3:
        t += '.' + fp
    if not ip and not fp:
        t = sign + '0'
    if rng.random() < 0.5:
        t += rng.choice('eE') + rng.choice(['', '+', '-']) + str(rng.randint(0, 40))
    if rng.random() < 0.1 and len(ip) > 1:
        t = t.replace(ip, ip[0] + '_' + ip[1:], 1)
    return t


lines = []
for i in range(1500):
    op = ['add', 'sub', 'mul', 'div', 'pow', 'cmp', 'floor', 'ceil', 'round', 'parse', 'float', 'from_float',
          'limit', 'float', 'limit'][i % 15]
    a, b = frac(), frac()
    if op == 'add':
        lines.append((op, s(a), s(b), s(a + b)))
    elif op == 'sub':
        lines.append((op, s(a), s(b), s(a - b)))
    elif op == 'mul':
        lines.append((op, s(a), s(b), s(a * b)))
    elif op == 'div':
        if b == 0:
            b = Fraction(3, 7)
        lines.append((op, s(a), s(b), s(a / b)))
    elif op == 'pow':
        e = rng.randint(-6, 6)
        if a == 0 and e < 0:
            e = -e
        lines.append((op, s(a), str(e), s(a ** e)))
    elif op == 'cmp':
        if rng.random() < 0.2:
            b = a
        lines.append((op, s(a), s(b), str((a > b) - (a < b))))
    elif op in ('floor', 'ceil', 'round'):
        if rng.random() < 0.3:
            a = Fraction(rng.randint(-20, 20), 2)
        r = {'floor': math.floor, 'ceil': math.ceil, 'round': round}[op](a)
        lines.append((op, s(a), '-', str(r)))
    elif op == 'parse':
        t = decimal_string()
        lines.append((op, t, '-', s(Fraction(t))))
    elif op == 'float':
        kind = rng.random()
        if kind < 0.2:
            a = Fraction(rng.getrandbits(60) | 1, 2 ** rng.randint(1070, 1140))  # subnormal or zero
        elif kind < 0.3:
            a = Fraction(rng.getrandbits(80), 1) * 2 ** rng.randint(900, 960)  # near overflow
        elif kind < 0.5:
            # exactly halfway between two doubles
            m = rng.getrandbits(53) | (1 << 52)
            a = Fraction(2 * m + 1, 2 ** rng.randint(1, 60))
        try:
            f = float(a)
        except OverflowError:
            f = math.inf if a > 0 else -math.inf  # Python raises OverflowError
        lines.append((op, s(a), '-', bits(f)))
    elif op == 'from_float':
        kind = rng.random()
        if kind < 0.3:
            x = struct.unpack('<d', struct.pack('<Q', rng.getrandbits(64)))[0]
            if math.isnan(x) or math.isinf(x):
                x = 1.5
        elif kind < 0.5:
            x = rng.uniform(-1, 1) * 2.0 ** -1060
        else:
            x = rng.uniform(-1000, 1000)
        lines.append((op, '0', bits(x), s(Fraction(x))))
    elif op == 'limit':
        if rng.random() < 0.5:
            a = Fraction(rng.uniform(-100, 100))
        md = rng.choice([1, 2, 3, 7, 10, 100, 1000, 10 ** 6, 10 ** 12, rng.randint(1, 10 ** 5)])
        if rng.random() < 0.1:
            # midway between two integers, with max 1: the floor
            a = Fraction(rng.randint(-50, 50) * 2 + 1, 2)
            md = 1
        lines.append((op, s(a), str(md), s(a.limit_denominator(md))))

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', '..', '..', '..', 'std', 'math', 'rational', 'testdata', 'cases.txt')
with open(out, 'w') as f:
    f.write('# generated by cmd/axiom/internal/tests/tools/gen_rational_tests.py: op a b result (Python %s fractions)\n'
            % '.'.join(map(str, __import__('sys').version_info[:3])))
    for line in lines:
        f.write(' '.join(line) + '\n')
