#!/usr/bin/env python3
"""Writes the tests of integer division and remainder by constants (which the
optimizer turns into multiplications, divconst.ax): for each integer type
and each of a list of divisors, a function of the dividend that divides by
the constant, and a check that compares its results with the divide
instruction's, by the same divisor read back from memory atomically
(volatile in C), which no optimization sees through:

    cmd/axiom/internal/tests/tools/gen_div_tests.py

writes cmd/axiom/internal/tests/run/div_const.ax and
cmd/axiom/internal/tests/c/run/div_const.c. The 8- and 16-bit types are
tested against every dividend (in C: with every 8-bit divisor), the 32- and
64-bit ones against the boundary values (0, 1, the largest and smallest,
the multiples of the divisor near 0 and near the largest value, and the
next one, wrapped, plus and minus one, and their negations) and pseudo-random dividends of every
magnitude, each with a list of divisors (and their negations for the signed
types). Each dividend goes through the forms the pass treats apart: x / d,
x % d, x % d == 0 alone, x / d and x % d together, and (32 and 64 bits) x
masked or shifted first, whose known bound selects smaller multipliers.
Each line of the output counts the results that differ.

    gen_div_tests.py --long <dir> [--16=k]

writes the longer versions (div_long.ax, div_long.c) into <dir>: every
8-bit divisor in both languages, more divisors and many more dividends;
with --16=k (0..15), only the 16-bit types, with every divisor in
[4096 k, 4096 (k + 1)) (signed: those less 32768).
"""
import os
import random
import sys

here = os.path.dirname(os.path.abspath(__file__))

TYPES = [  # name, bits, signed, C type
    ('u8', 8, False, 'unsigned char'),
    ('i8', 8, True, 'signed char'),
    ('u16', 16, False, 'unsigned short'),
    ('i16', 16, True, 'short'),
    ('u32', 32, False, 'unsigned'),
    ('i32', 32, True, 'int'),
    ('u64', 64, False, 'unsigned long long'),
    ('i64', 64, True, 'long long'),
]

BASE = [1, 2, 3, 5, 6, 7, 9, 10, 11, 12, 14, 25, 28, 100, 125, 255, 256, 641, 1000, 65535, 65536, 65537,
        10**9, 10**9 + 7, 3**20, 2**31 - 1, 2**31, 2**31 + 1, 2**32 - 1, 2**32 + 1, 10**18, 2**63 - 1, 2**63,
        2**63 + 1, 2**64 - 1, 0xCCCCCCCCCCCCCCCD]
BASE16 = list(range(1, 21)) + [25, 100, 125, 255, 256, 641, 1000, 10000, 16383, 16384, 21845, 32767, 32768,
                               32769, 43690, 65534, 65535]
BASE8 = list(range(1, 21)) + [25, 32, 37, 51, 63, 64, 65, 85, 100, 125, 127, 128, 129, 170, 200, 254, 255]


def divisors(bits, signed, extra, rng, every8, chunk16):
    lo, hi = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (1, (1 << bits) - 1)
    if bits == 8 and every8:
        ds = list(range(lo, hi + 1))
    elif bits == 16 and chunk16 is not None:
        ds = list(range(4096 * chunk16, 4096 * (chunk16 + 1)))
        if signed:
            ds = [d - 32768 for d in ds]
    else:
        base = {8: BASE8, 16: BASE16}.get(bits, BASE)
        ds = [d for d in base if d <= hi]
        if signed:
            ds += [-d for d in base[::2] + base[-3:] if -d >= lo]  # (every other one, and the largest)
            ds.append(lo)
        for _ in range(extra):
            k = rng.randrange(2, bits + 1)
            d = rng.randrange(1, 1 << (k - 1 if signed else k))
            if signed and rng.random() < 0.5:
                d = -d
            ds.append(d)
    out = []
    for d in ds:
        if d != 0 and lo <= d <= hi and d not in out:
            out.append(d)
    return out


def ax_lit(t, d):
    name, bits, signed, _ = t
    if signed and d == -(1 << (bits - 1)):
        return '@min_value(%s)' % name
    if d < 0:
        return '(-%d)' % -d
    return '%d' % d


def c_lit(t, d):
    name, bits, signed, _ = t
    if signed and d == -(1 << (bits - 1)):
        return {8: '(-127 - 1)', 16: '(-32767 - 1)', 32: '(-2147483647 - 1)', 64: '(-9223372036854775807LL - 1)'}[bits]
    if bits == 64:
        return '(%dLL)' % d if signed else '%dULL' % d
    if bits == 32 and not signed:
        return '%du' % d
    return '(%d)' % d


def tag(d):
    return ('m%d' % -d) if d < 0 else str(d)


def count_of(bits, nrand):
    return (1 << bits) if bits <= 16 else 48 + nrand


FIELDS = ['q', 'r', 'z', 'q4', 'r4', 'q5', 'z5', 'q6', 'r6']


def gen_axiom(sections, nrand):
    o = []
    w = o.append
    w('// Generated by cmd/axiom/internal/tests/tools/gen_div_tests.py: division and remainder by')
    w('// constants (divconst.ax: multiplications by reciprocals, shifts, compares) against the divide')
    w('// instruction, by the same divisor read back from memory atomically. Each line counts the')
    w('// results that differ: x / d, x % d, x % d == 0, x / d with x % d, and x masked or shifted.')
    w('// flags: -O1')
    w('import "../lib/io.ax" as io;')
    w('')
    w('let mut OPQ: u64 = 0;')
    w('')
    w('fn opq(v: u64) u64 {')
    w('    @atomic_store(&mut OPQ, v);')
    w('    return @atomic_load(&OPQ);')
    w('}')
    w('')
    w('fn next(s: *mut u64) u64 {')
    w('    let mut x = s.*;')
    w('    x ^= x << 13;')
    w('    x ^= x >> 7;')
    w('    x ^= x << 17;')
    w('    s.* = x;')
    w('    return x;')
    w('}')
    w('')
    for t, ds in sections:
        name, bits, signed, _ = t
        ut = 'u%d' % bits
        wide = bits >= 32
        k2 = '0x55' if bits == 8 else '0x2A5'
        fl = FIELDS if wide else FIELDS[:5]
        # the results of one dividend
        w('struct R_%s {' % name)
        for fld in fl:
            w('    %s: %s,' % (fld, 'bool' if fld[0] == 'z' else name))
        w('}')
        w('')

        # x / d ... for a divisor d, constant or not
        # (in f the dividends are x and x combined with o, which is 0: the
        # same values, which the compiler cannot tell are, so that each form
        # is computed alone)
        def forms(d, f_side):
            v = ['x', '(x +% o)', '(x -% o)', '(x ^ o)', '(x | o)', '(x +% (o << 1))', '(x ^ (o << 1))']
            if not f_side:
                v = ['x'] * len(v)
            f = ['%s / %s' % (v[0], d), '%s %% %s' % (v[1], d), '(%s %% %s) == 0' % (v[2], d), '%s / %s' % (v[3], d),
                 '%s %% %s' % (v[3], d)]
            if wide:
                f += ['(%s & 0xFFFFF) / %s' % (v[4], d), '((%s & 0xFFFFF) %% %s) != 0' % (v[5], d)]
                if signed:
                    zx = '@bit_cast(%s, @as(%s, @truncate(u16, @bit_cast(%s, %s))))' % (name, ut, ut, v[6])
                    f += ['%s / %s' % (zx, d), '%s %% %s' % (zx, d)]
                else:
                    f += ['(%s >> 5) / %s' % (v[6], d), '(%s >> 5) %% %s' % (v[6], d)]
            return f
        if wide:
            w('// dividend i for the divisor d')
            w('fn gen_%s(i: u64, s: *mut u64, d: %s) %s {' % (name, name, name))
            if signed:
                w('    let base: [12]%s = [0, 1, 2, 3, -1, -2, -3, @max_value(%s), @max_value(%s) - 1, @min_value(%s),' %
                  (name, name, name, name))
                w('                         @min_value(%s) + 1, @min_value(%s) + 2];' % (name, name))
            else:
                w('    let base: [12]%s = [0, 1, 2, 3, 4, 5, @max_value(%s), @max_value(%s) - 1, @max_value(%s) - 2,' %
                  (name, name, name, name))
                w('                         @max_value(%s) >> 1, (@max_value(%s) >> 1) + 1, (@max_value(%s) >> 1) + 2];' %
                  (name, name, name))
            w('    if i < 12 {')
            w('        return base[@int_cast(usize, i)];')
            w('    }')
            w('    if i < 48 {')
            w('        let k = i - 12;')
            w('        let m: [6]%s = [1, 2, 3, (@max_value(%s) / d) - 1, @max_value(%s) / d, (@max_value(%s) / d) +%% 1];' %
              (name, name, name, name))
            w('        let off = @bit_cast(%s, @truncate(%s, @bit_cast(u64, @bit_cast(i64, k %% 3) - 1)));' % (name, ut))
            w('        let mut x = (m[@int_cast(usize, (k % 18) / 3)] *% d) +% off;')
            w('        if k >= 18 {')
            w('            x = 0 -% x;')
            w('        }')
            w('        return x;')
            w('    }')
            w('    let r = next(s);')
            w('    let mut x = r >> @truncate(u32, (r >> 57) & 63);')
            w('    if ((r >> 56) & 1) != 0 {')
            w('        x = 0 -% x;')
            w('    }')
            w('    return @bit_cast(%s, @truncate(%s, x));' % (name, ut))
            w('}')
            w('')
        # the check: every dividend through f, against the divide instruction
        w('fn check_%s(f: fn(%s, %s) R_%s, d0: u64) u64 {' % (name, name, name, name))
        w('    let d = @bit_cast(%s, @truncate(%s, opq(d0)));' % (name, ut))
        w('    let o = @bit_cast(%s, @truncate(%s, opq(0)));' % (name, ut))
        w('    let mut bad: u64 = 0;')
        w('    let mut s: u64 = 0x9E3779B97F4A7C15 ^ d0;')
        w('    let mut i: u64 = 0;')
        w('    while i < %d {' % count_of(bits, nrand))
        if wide:
            w('        let x = gen_%s(i, &mut s, d);' % name)
        else:
            w('        let x = @bit_cast(%s, @truncate(%s, i));' % (name, ut))
        w('        let c = f(x, o);')
        for fld, e in zip(fl, forms('d', False)):
            w('        if c.%s != (%s) {' % (fld, e))
            w('            bad += 1;')
            w('        }')
        w('        i += 1;')
        w('    }')
        w('    return bad;')
        w('}')
        w('')
        for d in ds:
            dl = ax_lit(t, d)
            w('fn %s_%s(x: %s, o: %s) R_%s {' % (name, tag(d), name, name, name))
            w('    return R_%s.{' % name)
            for fld, e in zip(fl, forms(dl, True)):
                w('        %s: %s,' % (fld, e))
            w('    };')
            w('}')
            w('')
        w('fn all_%s() u64 {' % name)
        w('    let mut bad: u64 = 0;')
        for d in ds:
            w('    bad += check_%s(%s_%s, %d);' % (name, name, tag(d), d & ((1 << bits) - 1)))
        w('    return bad;')
        w('}')
        w('')
    w('export fn run() void {')
    lines = []
    for t, ds in sections:
        lines.append(('    io.str("%s %d divisors");' % (t[0], len(ds)), 'expect: %s %d divisors' % (t[0], len(ds))))
        lines.append(('    io.uint(all_%s());' % t[0], 'expect: 0'))
    col = max(len(c) for c, _ in lines) + 2
    for c, e in lines:
        w(c.ljust(col) + '// ' + e)
    w('}')
    return '\n'.join(o) + '\n'


def gen_c(sections, nrand):
    o = []
    w = o.append
    w('/* flags: -O1 */')
    w('/* Generated by cmd/axiom/internal/tests/tools/gen_div_tests.py: division and remainder by')
    w('   constants (the optimizer\'s multiplications by reciprocals, shifts and compares) against the')
    w('   divide instruction, by the same divisor read back from a volatile object. Each line counts')
    w('   the results that differ: x / d, x % d, x % d == 0, x / d with x % d, and x masked or')
    w('   shifted. The 8- and 16-bit types are promoted to int first. C\'s MIN / -1 is undefined: it')
    w('   is left out. */')
    w('#include "host.h"')
    w('')
    w('static volatile unsigned long long OPQ;')
    w('')
    w('static unsigned long long opq(unsigned long long v) {')
    w('    OPQ = v;')
    w('    return OPQ;')
    w('}')
    w('')
    w('static unsigned long long next(unsigned long long *s) {')
    w('    unsigned long long x = *s;')
    w('    x ^= x << 13;')
    w('    x ^= x >> 7;')
    w('    x ^= x << 17;')
    w('    *s = x;')
    w('    return x;')
    w('}')
    w('')
    for t, ds in sections:
        name, bits, signed, ct = t
        wide = bits >= 32
        uct = {8: 'unsigned', 16: 'unsigned', 32: 'unsigned', 64: 'unsigned long long'}[bits]
        if wide:
            mx = {(32, False): '0xFFFFFFFFu', (32, True): '0x7FFFFFFF', (64, False): '0xFFFFFFFFFFFFFFFFULL',
                  (64, True): '0x7FFFFFFFFFFFFFFFLL'}[(bits, signed)]
            mn = {(32, True): '(-0x7FFFFFFF - 1)', (64, True): '(-0x7FFFFFFFFFFFFFFFLL - 1)'}.get((bits, signed), '0')
            w('static %s gen_%s(unsigned long long i, unsigned long long *s, %s d) {' % (ct, name, ct))
            if signed:
                w('    static const %s base[12] = { 0, 1, 2, 3, -1, -2, -3, %s, %s - 1, %s, %s + 1, %s + 2 };' %
                  (ct, mx, mx, mn, mn, mn))
            else:
                w('    static const %s base[12] = { 0, 1, 2, 3, 4, 5, %s, %s - 1, %s - 2, %s >> 1, (%s >> 1) + 1,' %
                  (ct, mx, mx, mx, mx, mx))
                w('                                 (%s >> 1) + 2 };' % mx)
            w('    if (i < 12) return base[i];')
            w('    if (i < 48) {')
            w('        unsigned long long k = i - 12;')
            w('        %s m[6] = { 1, 2, 3, (%s)(%s / d) - 1, (%s)(%s / d), (%s)(%s / d) + 1 };' % (uct, uct, mx, uct, mx, uct, mx))
            w('        %s x = m[(k %% 18) / 3] * (%s)d + (%s)((long long)(k %% 3) - 1);' % (uct, uct, uct))
            w('        if (k >= 18) x = 0 - x;')
            w('        return (%s)x;' % ct)
            w('    }')
            w('    {')
            w('        unsigned long long r = next(s);')
            w('        unsigned long long x = r >> ((r >> 57) & 63);')
            w('        if ((r >> 56) & 1) x = 0 - x;')
            w('        return (%s)(%s)x;' % (ct, uct))
            w('    }')
            w('}')
            w('')
        mn = {32: '(-0x7FFFFFFF - 1)', 64: '(-0x7FFFFFFFFFFFFFFFLL - 1)'}.get(bits)
        # x combined with o, which is 0: the same values, which the compiler
        # cannot tell are, so that each form by the constant D is computed alone
        for k, e in enumerate(['x + o', 'x - o', 'x ^ o', 'x | o', 'x + (o << 1)', 'x ^ (o << 1)']):
            w('#define X%d_%s ((%s)(%s))' % (k + 1, name, ct, e.replace('x', '(%s)x' % uct, 1)))

        def ok(v):
            # (MIN / -1 and MIN % -1 left out)
            return ('(D != -1 || %s != %s) && ' % (v, mn)) if (signed and wide) else ''
        X = lambda k: 'X%d_%s' % (k, name)
        checks = [
            '%s(x / D) != (x / d)' % ok('x'),
            '%s(%s %% D) != (x %% d)' % (ok('x'), X(1)),
            '%s((%s %% D) == 0) != ((x %% d) == 0)' % (ok('x'), X(2)),
            '%s((%s / D) != (x / d) || (%s %% D) != (x %% d))' % (ok('x'), X(3), X(3)),
        ]
        if wide:
            checks.append('((%s & 0xFFFFF) / D) != ((x & 0xFFFFF) / d) || '
                          '((%s & 0xFFFFF) %% D != 0) != ((x & 0xFFFFF) %% d != 0)' % (X(4), X(5)))
            if not signed:
                checks.append('((%s >> 5) / D) != ((x >> 5) / d) || ((%s >> 5) %% D) != ((x >> 5) %% d)' % (X(6), X(6)))
        w('#define T_%s(F, D) \\' % name)
        w('    static unsigned long long F(void) { \\')
        w('        %s d = (%s)opq((unsigned long long)(D)); \\' % (ct, ct))
        w('        %s o = (%s)opq(0); \\' % (uct, uct))
        w('        unsigned long long bad = 0, s = 0x9E3779B97F4A7C15ULL ^ (unsigned long long)(D), i; \\')
        w('        for (i = 0; i < %dULL; i++) { \\' % count_of(bits, nrand))
        if wide:
            w('            %s x = gen_%s(i, &s, d); \\' % (ct, name))
        else:
            w('            %s x = (%s)i; \\' % (ct, ct))
        for c in checks:
            w('            if (%s) bad++; \\' % c)
        w('        } \\')
        w('        return bad; \\')
        w('    }')
        w('')
        for d in ds:
            w('T_%s(t_%s_%s, %s)' % (name, name, tag(d), c_lit(t, d)))
        w('')
        w('static unsigned long long all_%s(void) {' % name)
        w('    unsigned long long bad = 0;')
        for d in ds:
            w('    bad += t_%s_%s();' % (name, tag(d)))
        w('    return bad;')
        w('}')
        w('')
    w('int main(void) {')
    for t, ds in sections:
        label = '%s %d divisors' % (t[0], len(ds))
        w('    print_str("%s", %d);' % (label, len(label)))
        w('    print_u64(all_%s());' % t[0])
    w('    return 0;')
    w('}')
    for t, ds in sections:
        w('/* expect: %s %d divisors */' % (t[0], len(ds)))
        w('/* expect: 0 */')
    return '\n'.join(o) + '\n'


def main():
    args = sys.argv[1:]
    long_dir = None
    chunk = None
    if args and args[0] == '--long':
        long_dir = args[1]
        for a in args[2:]:
            if a.startswith('--16='):
                chunk = int(a.split('=')[1])
    rng = random.Random(20261112 + (chunk or 0))
    extra = 60 if long_dir else 6
    nrand = 100000 if long_dir else 500
    sections = []
    for t in TYPES:
        if chunk is not None and t[1] != 16:
            continue
        sections.append((t, divisors(t[1], t[2], extra, rng, long_dir is not None, chunk)))
    if long_dir:
        ax = gen_axiom(sections, nrand).replace('"../lib/io.ax"', '"io.ax"')
        open(os.path.join(long_dir, 'div_long.ax'), 'w').write(ax)
        open(os.path.join(long_dir, 'div_long.c'), 'w').write(gen_c(sections, nrand))
        return
    open(os.path.join(here, '..', 'run', 'div_const.ax'), 'w').write(gen_axiom(sections, nrand))
    # C: every 8-bit divisor (a line each)
    csections = [(t, divisors(8, t[2], 0, rng, True, None) if t[1] == 8 else ds) for t, ds in sections]
    open(os.path.join(here, '..', 'c', 'run', 'div_const.c'), 'w').write(gen_c(csections, nrand))


main()
