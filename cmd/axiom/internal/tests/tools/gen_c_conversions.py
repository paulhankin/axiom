#!/usr/bin/env python3
"""Writes the C front end's tests of the integer promotions and the usual
arithmetic conversions (C17 6.3.1.1, 6.3.1.8), computed here from the
standard's rules for each choice of int, long and char:

    cmd/axiom/internal/tests/tools/gen_c_conversions.py

writes cmd/axiom/internal/tests/c/run/conv_<config>.c. Each test prints, for
every arithmetic type T (and an enumeration, compatible with unsigned int),
the type of +x, -x, ~x and !x; and for every pair (T1, T2) the type of
x1 + x2, of x1 << x2 and of c ? x1 : x2, whether (T1)-1 < (T2)1, and the
value of (T1)-1 + (T2)0 converted to unsigned long long. A type is printed
as its number in TYPES (through _Generic, so the tests are C11). The
int32_long64 configuration is the one of the usual 64-bit C ABIs; its
expected output can be checked with the system's C compiler.
"""
import os

out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'c', 'run')

# name, C spelling, rank (6.3.1.1p1), whether signed (None: by config), width (None: by config)
TYPES = [
    ('char', 'char', 1), ('schar', 'signed char', 1), ('uchar', 'unsigned char', 1),
    ('short', 'short', 2), ('ushort', 'unsigned short', 2), ('int', 'int', 3), ('uint', 'unsigned', 3),
    ('long', 'long', 4), ('ulong', 'unsigned long', 4), ('llong', 'long long', 5),
    ('ullong', 'unsigned long long', 5), ('float', 'float', 10), ('double', 'double', 11),
    ('ldouble', 'long double', 12), ('bool', '_Bool', 0),
]
IDS = {t[0]: i + 1 for i, t in enumerate(TYPES)}
OPERANDS = [t[0] for t in TYPES] + ['enum']
CONFIGS = [
    ('int32_long64', '--c-int=32 --c-long=64', 32, 64, True),
    ('int32_long32', '--c-int=32 --c-long=32', 32, 32, True),
    ('int16_long32', '--c-int=16 --c-long=32', 16, 32, True),
    ('int64_long64', '--c-int=64 --c-long=64', 64, 64, True),
    ('uchar', '--c-char=unsigned --c-int=32 --c-long=64', 32, 64, False),
]


class Config:
    def __init__(self, ib, lb, char_signed):
        self.ib, self.lb, self.char_signed = ib, lb, char_signed

    def bits(self, t):
        return {'bool': 1, 'char': 8, 'schar': 8, 'uchar': 8, 'short': 16, 'ushort': 16, 'int': self.ib,
                'uint': self.ib, 'long': self.lb, 'ulong': self.lb, 'llong': 64, 'ullong': 64}[t]

    def signed(self, t):
        if t == 'char':
            return self.char_signed
        return t in ('schar', 'short', 'int', 'long', 'llong')

    def is_float(self, t):
        return t in ('float', 'double', 'ldouble')

    def rank(self, t):
        return next(r for n, _, r in TYPES if n == t)

    def promote(self, t):
        if t == 'enum':
            t = 'uint'
        if self.is_float(t) or self.rank(t) >= 3:
            return t
        # int holds every value of a narrower type, and of one as wide that is signed
        bits = 1 if t == 'bool' else self.bits(t)
        if bits < self.ib or self.signed(t):
            return 'int'
        return 'uint'

    def unsigned_of(self, t):
        return {'int': 'uint', 'long': 'ulong', 'llong': 'ullong'}[t]

    def common(self, a, b):
        a, b = self.promote(a), self.promote(b)
        for f in ('ldouble', 'double', 'float'):
            if f in (a, b):
                return f
        if a == b:
            return a
        if self.signed(a) == self.signed(b):
            return a if self.rank(a) >= self.rank(b) else b
        s, u = (a, b) if self.signed(a) else (b, a)
        if self.rank(u) >= self.rank(s):
            return u
        if self.bits(s) > self.bits(u):
            return s
        return self.unsigned_of(s)

    def conv(self, t, v):
        """Integer v converted to integer type t (a signed result wraps)."""
        if t == 'enum':
            t = 'uint'
        if t == 'bool':
            return 1 if v else 0
        n = self.bits(t)
        v &= (1 << n) - 1
        if self.signed(t) and v >= 1 << (n - 1):
            v -= 1 << n
        return v


def type_id(t):
    return IDS['uint' if t == 'enum' else t]


def spelling(t):
    return 'enum E' if t == 'enum' else next(s for n, s, _ in TYPES if n == t)


def generate(name, flags, ib, lb, char_signed):
    c = Config(ib, lb, char_signed)
    out = []
    expect = []
    out.append('/* flags: --c-std=c11 %s */' % flags)
    out.append('/* Generated by cmd/axiom/internal/tests/tools/gen_c_conversions.py: the integer')
    out.append('   promotions and the usual arithmetic conversions (6.3.1.1, 6.3.1.8) with')
    out.append('   %s. */' % flags)
    out.append('#include "host.h"')
    out.append('')
    gen = ', '.join('%s: %d' % (s, IDS[n]) for n, s, _ in TYPES)
    out.append('#define T(x) _Generic((x), %s, default: 0)' % gen)
    out.append('')
    out.append('enum E { E0, E1 };')
    out.append('volatile int c = 1;')
    out.append('')
    out.append('int main(void) {')
    for t in OPERANDS:
        out.append('    {')
        out.append('        %s x = 1;' % spelling(t))
        out.append('        print_i64(T(+x) * 100 + T(-x));')
        expect.append(type_id(c.promote(t)) * 100 + type_id(c.promote(t)))
        if not c.is_float(t):
            out.append('        print_i64(T(~x));')
            expect.append(type_id(c.promote(t)))
        out.append('        print_i64(T(!x));')
        expect.append(IDS['int'])
        out.append('    }')
    for a in OPERANDS:
        for b in OPERANDS:
            ints = not c.is_float(a) and not c.is_float(b)
            out.append('    {')
            out.append('        %s x = 1;' % spelling(a))
            out.append('        %s y = 1;' % spelling(b))
            r = c.common(a, b)
            line = 'T(x + y) * 10000LL + T(c ? x : y) * 100LL'
            val = type_id(r) * 10000 + type_id(r) * 100
            if ints:
                line += ' + T(x << y)'
                val += type_id(c.promote(a))
            out.append('        print_i64(%s);' % line)
            expect.append(val)
            if ints:
                out.append('        print_i64((%s)-1 < (%s)1);' % (spelling(a), spelling(b)))
                expect.append(1 if c.conv(r, c.conv(a, -1)) < c.conv(r, c.conv(b, 1)) else 0)
                out.append('        print_u64((unsigned long long)((%s)-1 + (%s)0));' % (spelling(a), spelling(b)))
                expect.append(c.conv(r, c.conv(r, c.conv(a, -1)) + c.conv(r, c.conv(b, 0))) & ((1 << 64) - 1))
            out.append('    }')
    out.append('    return 0;')
    out.append('}')
    out.append('')
    for v in expect:
        out.append('/* expect: %d */' % v)
    with open(os.path.join(out_dir, 'conv_%s.c' % name), 'w') as f:
        f.write('\n'.join(out) + '\n')


for cfg in CONFIGS:
    generate(*cfg)
