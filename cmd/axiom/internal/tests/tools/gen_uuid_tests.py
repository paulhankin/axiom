#!/usr/bin/env python3
"""Generates std/encoding/uuid/testdata/cases.txt from Python's uuid module.

    cmd/axiom/internal/tests/tools/gen_uuid_tests.py

Lines (fields separated by single spaces):

    v3 <namespace> <name as hex> <uuid>        uuid.uuid3
    v5 <namespace> <name as hex> <uuid>        uuid.uuid5
    parse <text> <uuid> <version> <variant>    uuid.UUID(text); variant 0 NCS,
                                               1 RFC 4122, 2 Microsoft, 3 future
    bad <text>                                 uuid.UUID(text) raises ValueError

Python's UUID() also takes hyphens in any position; the cases here keep to
the forms std/encoding/uuid accepts (canonical, braces, urn:uuid:, 32 hex
digits).
"""
import hashlib
import os
import random
import uuid

out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', '..', 'std', 'encoding', 'uuid', 'testdata',
                        'cases.txt')
rng = random.Random(9562)
VARIANTS = {uuid.RESERVED_NCS: 0, uuid.RFC_4122: 1, uuid.RESERVED_MICROSOFT: 2, uuid.RESERVED_FUTURE: 3}
NAMESPACES = [uuid.NAMESPACE_DNS, uuid.NAMESPACE_URL, uuid.NAMESPACE_OID, uuid.NAMESPACE_X500]

lines = ['# generated by cmd/axiom/internal/tests/tools/gen_uuid_tests.py from Python\'s uuid module; do not edit']
names = [b'', b'a', b'python.org', b'http://example.com/', b'1.3.6.1', b'cn=John Smith, o=Example',
         'café'.encode(), bytes(range(256))]
for _ in range(40):
    names.append(bytes(rng.randrange(256) for _ in range(rng.randrange(1, 120))))


def name_based(ns, name, version):
    """uuid.uuid3 / uuid.uuid5, for names that are not UTF-8 text too (the same formula)."""
    try:
        text = name.decode('utf-8')
    except UnicodeDecodeError:
        h = (hashlib.md5 if version == 3 else hashlib.sha1)(ns.bytes + name).digest()
        return uuid.UUID(bytes=h[:16], version=version)
    return uuid.uuid3(ns, text) if version == 3 else uuid.uuid5(ns, text)


for i, name in enumerate(names):
    ns = NAMESPACES[i % 4] if i % 5 else uuid.UUID(int=rng.getrandbits(128))
    lines.append('v3 %s %s %s' % (ns, name.hex(), name_based(ns, name, 3)))
    lines.append('v5 %s %s %s' % (ns, name.hex(), name_based(ns, name, 5)))

# the name-based functions on str names agree with the byte forms above
assert str(uuid.uuid5(uuid.NAMESPACE_DNS, 'python.org')) == '886313e1-3b8a-5372-9b90-0c9aee199e5d'
assert str(uuid.uuid3(uuid.NAMESPACE_DNS, 'python.org')) == '6fa459ea-ee8a-3ca4-894e-db77e160355e'

for _ in range(60):
    u = uuid.UUID(int=rng.getrandbits(128))
    s = str(u)
    form = rng.randrange(6)
    if form == 1:
        s = s.upper()
    elif form == 2:
        s = '{' + s + '}'
    elif form == 3:
        s = 'urn:uuid:' + s
    elif form == 4:
        s = u.hex
    elif form == 5:
        s = ''.join(c.upper() if rng.random() < 0.5 else c for c in s)
    p = uuid.UUID(s)
    lines.append('parse %s %s %d %d' % (s, p, p.version if p.version is not None else (p.int >> 76) & 15,
                                        VARIANTS[p.variant]))
for s in ['00000000-0000-0000-0000-000000000000', 'ffffffff-ffff-ffff-ffff-ffffffffffff',
          'urn:uuid:6FA459EA-EE8A-3CA4-894E-DB77E160355E', '{6fa459ea-ee8a-3ca4-894e-db77e160355e}']:
    p = uuid.UUID(s)
    lines.append('parse %s %s %d %d' % (s, p, (p.int >> 76) & 15, VARIANTS[p.variant]))
bad = ['', '6fa459ea-ee8a-3ca4-894e-db77e160355', '6fa459ea-ee8a-3ca4-894e-db77e160355e0',
       '6fa459ea-ee8a-3ca4-894e-db77e160355g', 'urn:uuid:{6fa459ea-ee8a-3ca4-894e-db77e160355e}x',
       'x6fa459eaee8a3ca4894edb77e160355e',
       '6fa459eaee8a3ca4894edb77e160355']
for s in bad:
    try:
        uuid.UUID(s)
        raise SystemExit('unexpectedly valid: ' + s)
    except ValueError:
        pass
    if s:
        lines.append('bad ' + s)
with open(out_path, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote %d lines to %s' % (len(lines), out_path))
