#!/usr/bin/env python3
"""Generates std/text/similarity/testdata/cases.txt: string distances and
difflib similarities of random strings, compared by code point.

Each line is tab-separated: op a b result
  ratio   difflib.SequenceMatcher(None, a, b).ratio() (repr)
  blocks  its get_matching_blocks(), as "a,b,size;" for each
  lev osa dl lcs substr   Levenshtein, optimal string alignment and
          unrestricted Damerau-Levenshtein distances, the lengths of a longest
          common subsequence and substring (reference implementations below)
"""
import difflib
import os
import random

rng = random.Random(77)
ALPHABETS = ['ab', 'abc', 'abcdefgh', 'abcdefghijklmnopqrstuvwxyz ', 'aäbçé日本語🙂']


def rand_str(maxlen):
    alpha = rng.choice(ALPHABETS)
    return ''.join(rng.choice(alpha) for _ in range(rng.randint(0, maxlen)))


def mutate(s):
    s = list(s)
    alpha = 'abcxyzé日'
    for _ in range(rng.randint(0, 5)):
        k = rng.random()
        i = rng.randint(0, len(s))
        if k < 0.3:
            s.insert(i, rng.choice(alpha))
        elif k < 0.5 and s:
            del s[min(i, len(s) - 1)]
        elif k < 0.7 and len(s) > 1:
            i = min(i, len(s) - 2)
            s[i], s[i + 1] = s[i + 1], s[i]
        elif s:
            s[min(i, len(s) - 1)] = rng.choice(alpha)
    return ''.join(s)


def lev(a, b):
    prev = list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] != b[j - 1]))
        prev = cur
    return prev[len(b)]


def osa(a, b):
    d = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(len(a) + 1):
        d[i][0] = i
    for j in range(len(b) + 1):
        d[0][j] = j
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            cost = a[i - 1] != b[j - 1]
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + cost)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                d[i][j] = min(d[i][j], d[i - 2][j - 2] + 1)
    return d[len(a)][len(b)]


def dl(a, b):
    # Lowrance-Wagner, as on Wikipedia
    da = {}
    maxdist = len(a) + len(b)
    d = [[0] * (len(b) + 2) for _ in range(len(a) + 2)]
    d[0][0] = maxdist
    for i in range(len(a) + 1):
        d[i + 1][0] = maxdist
        d[i + 1][1] = i
    for j in range(len(b) + 1):
        d[0][j + 1] = maxdist
        d[1][j + 1] = j
    for i in range(1, len(a) + 1):
        db = 0
        for j in range(1, len(b) + 1):
            k = da.get(b[j - 1], 0)
            l = db
            if a[i - 1] == b[j - 1]:
                cost = 0
                db = j
            else:
                cost = 1
            d[i + 1][j + 1] = min(d[i][j] + cost, d[i + 1][j] + 1, d[i][j + 1] + 1,
                                  d[k][l] + (i - k - 1) + 1 + (j - l - 1))
        da[a[i - 1]] = i
    return d[len(a) + 1][len(b) + 1]


def lcs(a, b):
    prev = [0] * (len(b) + 1)
    for i in range(len(a)):
        cur = [0] * (len(b) + 1)
        for j in range(len(b)):
            cur[j + 1] = prev[j] + 1 if a[i] == b[j] else max(prev[j + 1], cur[j])
        prev = cur
    return prev[len(b)]


def substr(a, b):
    best = 0
    prev = [0] * (len(b) + 1)
    for i in range(len(a)):
        cur = [0] * (len(b) + 1)
        for j in range(len(b)):
            if a[i] == b[j]:
                cur[j + 1] = prev[j] + 1
                best = max(best, cur[j + 1])
        prev = cur
    return best


lines = []
for i in range(700):
    op = ['ratio', 'blocks', 'lev', 'osa', 'dl', 'lcs', 'substr'][i % 7]
    if op in ('ratio', 'blocks') and rng.random() < 0.25:
        # long b: difflib's automatic junk heuristic applies from 200 elements
        a = rand_str(300)
        b = mutate(a) + rand_str(250)
        if len(b) < 200:
            b += 'a' * 200
    else:
        a = rand_str(20)
        b = mutate(a) if rng.random() < 0.6 else rand_str(20)
    if op == 'ratio':
        r = repr(difflib.SequenceMatcher(None, a, b).ratio())
    elif op == 'blocks':
        r = ''.join('%d,%d,%d;' % tuple(m) for m in difflib.SequenceMatcher(None, a, b).get_matching_blocks())
    else:
        r = str({'lev': lev, 'osa': osa, 'dl': dl, 'lcs': lcs, 'substr': substr}[op](a, b))
    lines.append('\t'.join([op, a, b, r]))

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', '..', '..', '..', 'std', 'text', 'similarity', 'testdata', 'cases.txt')
with open(out, 'w', encoding='utf-8') as f:
    f.write('# generated by cmd/axiom/internal/tests/tools/gen_similarity_tests.py: op\\ta\\tb\\tresult\n')
    for line in lines:
        f.write(line + '\n')
