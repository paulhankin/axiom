#include <stdint.h>
#include "host.h"
#define ALL(x) print_u64(stdc_leading_zeros(x)); print_u64(stdc_leading_ones(x)); print_u64(stdc_trailing_zeros(x)); \
    print_u64(stdc_trailing_ones(x)); print_u64(stdc_first_leading_zero(x)); print_u64(stdc_first_leading_one(x)); \
    print_u64(stdc_first_trailing_zero(x)); print_u64(stdc_first_trailing_one(x)); print_u64(stdc_count_zeros(x)); \
    print_u64(stdc_count_ones(x)); print_u64(stdc_has_single_bit(x)); print_u64(stdc_bit_width(x)); \
    print_u64(stdc_bit_floor(x)); print_u64(stdc_bit_ceil(x))
int main(void) {
    unsigned char c[] = { 0, 1, 0x80, 0xff, 0x31 };
    unsigned short s[] = { 0, 3, 0x8000, 0xffff, 0x0f00 };
    unsigned int u[] = { 0, 1, 0x80000000u, 0xffffffffu, 0x00f00000u };
    unsigned long long l[] = { 0, 5, 0x8000000000000000ull, 0xffffffffffffffffull, 0x10ull };
    int i;
    for (i = 0; i < 5; i++) { ALL(c[i]); ALL(s[i]); ALL(u[i]); ALL(l[i]); }
    print_u64(stdc_leading_zeros_uc(1)); print_u64(stdc_bit_ceil_us(300)); print_u64(stdc_bit_floor_ull(1000));
    print_u64(stdc_count_ones_ul(0xF0F0ul)); print_u64(stdc_has_single_bit_ui(64)); print_u64(stdc_first_trailing_one_uc(0x40));
    print_u64(sizeof(stdc_bit_floor((unsigned char)7))); print_u64(sizeof(stdc_leading_zeros((unsigned long long)1)));
    print_u64(__STDC_ENDIAN_NATIVE__ == __STDC_ENDIAN_LITTLE__);
    return 0;
}

