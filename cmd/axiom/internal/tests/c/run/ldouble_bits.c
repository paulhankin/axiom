union bits {
    long double x;
    u64 h[2];
};

static long double mk(u64 lo, u64 hi) {
    union bits u;
    u.h[0] = lo;
    u.h[1] = hi;
    return u.x;
}

static int is_nan(u64 lo, u64 hi) {
#if __AXIOM_LDBL_WIDTH__ == 80
    return (hi & 0x7fff) == 0x7fff && (lo << 1) != 0;
#else
    return ((hi >> 48) & 0x7fff) == 0x7fff && (((hi << 16) | lo) != 0);
#endif
}

/* r is the expected value: the same bits, or (binary128, where the
   platform's NaN results are not specified bit for bit) a NaN for a NaN */
static int same(long double r, const struct v *e) {
    union bits u;
    u.x = r;
    if (__AXIOM_LDBL_WIDTH__ == 128 && is_nan(e->rlo, e->rhi))
        return is_nan(u.h[0], u.h[1]);
    return u.h[0] == e->rlo && (u.h[1] & HI_MASK) == e->rhi;
}

#define N(t) (sizeof t / sizeof t[0])

static int binary(const struct v *t, unsigned n, int op) {
    int bad = 0;
    unsigned k;
    for (k = 0; k < n; k++) {
        long double a = mk(t[k].alo, t[k].ahi), b = mk(t[k].blo, t[k].bhi), r;
        if (op == 0) r = a + b;
        else if (op == 1) r = a - b;
        else if (op == 2) r = a * b;
        else r = a / b;
        bad += !same(r, &t[k]);
    }
    return bad;
}

static int compares(void) {
    int bad = 0;
    unsigned k;
    for (k = 0; k < N(cmp_v); k++) {
        long double a = mk(cmp_v[k].alo, cmp_v[k].ahi), b = mk(cmp_v[k].blo, cmp_v[k].bhi);
        u64 c = a < b ? 1 : a == b ? 2 : a > b ? 3 : 4;
        /* (each relation on its own agrees) */
        bad += c != cmp_v[k].rlo;
        bad += (a <= b) != (c == 1 || c == 2) || (a >= b) != (c == 2 || c == 3) || (a != b) != (c != 2);
    }
    return bad;
}

static int conversions(void) {
    int bad = 0;
    unsigned k;
    for (k = 0; k < N(from_i64_v); k++)
        bad += !same((long double)(long long)from_i64_v[k].alo, &from_i64_v[k]);
    for (k = 0; k < N(from_u64_v); k++)
        bad += !same((long double)from_u64_v[k].alo, &from_u64_v[k]);
    for (k = 0; k < N(to_i64_v); k++)
        bad += (u64)(long long)mk(to_i64_v[k].alo, to_i64_v[k].ahi) != to_i64_v[k].rlo;
    for (k = 0; k < N(to_u64_v); k++)
        bad += (u64)mk(to_u64_v[k].alo, to_u64_v[k].ahi) != to_u64_v[k].rlo;
    for (k = 0; k < N(to_f64_v); k++) {
        union { double d; u64 h; } d;
        d.d = (double)mk(to_f64_v[k].alo, to_f64_v[k].ahi);
        if (__AXIOM_LDBL_WIDTH__ == 128 && (to_f64_v[k].rlo << 1) > 0xffe0000000000000ull)
            bad += !((d.h << 1) > 0xffe0000000000000ull); /* (a NaN) */
        else
            bad += d.h != to_f64_v[k].rlo;
    }
    for (k = 0; k < N(to_f32_v); k++) {
        union { float f; unsigned h; } f;
        f.f = (float)mk(to_f32_v[k].alo, to_f32_v[k].ahi);
        if (__AXIOM_LDBL_WIDTH__ == 128 && (to_f32_v[k].rlo & 0x7fffffff) > 0x7f800000)
            bad += !((f.h & 0x7fffffff) > 0x7f800000);
        else
            bad += f.h != to_f32_v[k].rlo;
    }
    for (k = 0; k < N(from_f64_v); k++) {
        union { double d; u64 h; } d;
        d.h = from_f64_v[k].alo;
        bad += !same((long double)d.d, &from_f64_v[k]);
    }
    for (k = 0; k < N(from_f32_v); k++) {
        union { float f; unsigned h; } f;
        f.h = (unsigned)from_f32_v[k].alo;
        bad += !same((long double)f.f, &from_f32_v[k]);
    }
    return bad;
}
